"""День, на который смотрят с экрана этажа, — и период плана вокруг него.

Слой сроков договоров и счёт свободного считаются не «сейчас», а на названный день:
«что освобождается к январю» — вопрос, который экрану задают, а не считают в уме по
списку договоров. Назван день адресом экрана (`?date=`), как и слой, и по той же
причине: «третий этаж, сроки, на 1 января» пересылают ссылкой, и открывший её видит
ровно то же. Принадлежит день при этом экрану, а не слою: счёт свободного стоит рядом
с чертежом при любом слое и считается на выбранный день всегда.

Осей времени при этом две, и они намеренно не смешиваются (ADR 0010). План на экране —
всегда план, действующий сегодня: работы планируют по сегодняшнему чертежу, и
назначенная на будущее перепланировка до своей даты не рисуется (ADR 0004). Ответ же
считается на выбранный день. Там, где выбранный день лежит вне периода плана, экран об
этом говорит (`outside_the_plan`): сегодняшний чертёж с завтрашним арендатором,
показанный молча, и есть та самая склейка двух осей, которой здесь не происходит.
"""

from datetime import date

from django.utils.dateparse import parse_date


def named_by(address, today: date) -> date:
    """День, названный адресом экрана; неназванный и нечитаемый — сегодняшний.

    Сегодняшний день передаётся, а не спрашивается здесь: он берётся один раз на весь
    экран, иначе запрос, пришедшийся на полночь, посчитал бы слой на один день, а
    чертёж выбрал бы за другой.

    Адрес пересылают и правят руками, поэтому опечатка в дате открывает экран на
    сегодняшнем дне, а не ошибкой: сломать экран правкой его адреса не должно быть
    возможно — то же правило, что и у имени слоя (`plan_layer.chosen_by`).
    """
    try:
        chosen = parse_date(address.get("date", ""))
    except ValueError:
        # «2026-02-30» — день, записанный как день, но не существующий: `parse_date`
        # отличает его от невнятицы отказом, а экрану разница безразлична.
        chosen = None
    return chosen or today


def outside_the_plan(plan, day: date) -> str | None:
    """Что сказать, если выбранный день лежит вне периода плана на экране, иначе `None`.

    Говорится это ровно тогда, когда оси времени расходятся: планировка на выбранный
    день могла быть другой, чем на чертеже, который экран показывает. Молчать об этом
    значило бы выдать сегодняшний чертёж за чертёж выбранного дня.

    Принадлежность дню спрашивается у самого плана: правило периода лежит на нём, и
    переписанное здесь сравнение дат стало бы третьим описанием одного правила.

    У этажа без действующего плана предупреждать не о чем: на экране нет чертежа,
    который можно было бы принять за чертёж выбранного дня.
    """
    if plan is None or plan.in_force_on(day):
        return None
    return (
        f"Выбран {day:%d.%m.%Y}, а план на экране действует {plan.period}: "
        f"экран этажа показывает планировку, действующую сегодня, и на выбранный "
        f"день она могла быть другой."
    )
