"""Слой: правило, по которому окрашиваются контуры поэтажного плана.

Слой даёт каждому контуру три вещи разом — цвет заливки, запись в легенде и строку
подсказки, — и считается он на сервере. Иначе правило разъезжается: браузер знал бы,
каким цветом красить, а легенда рядом с планом объясняла бы цвета по своему списку,
и разойтись им ничто бы не мешало.

Здесь заведены два слоя — тип помещения и сроки договоров. Один план отвечает на два
вопроса: как этаж устроен и в каком он коммерческом состоянии. Долги арендаторов и
неисправности инженерных систем придут позже такими же слоями на тот же план, а не
новыми экранами: экран рисует то, что слой ему дал (`Painting`), и о самом правиле не
знает. План показывает один слой за раз.

Который именно — сказано адресом экрана (`LAYERS`, `choices`): слой в адресе значит,
что коллега открывает ровно тот вид, на который вы смотрите. Регистрация слоя — строка
в реестре, и экрану для нового слоя не нужно ничего, кроме неё: имя из адреса, название
для переключателя и сборка — всё в одной строке.

Собирается слой тем, что ему нужно, из экрана, который его спросил (`Screen`): типу
помещения хватает самих контуров, срокам договоров нужны день и договоры, видимые
спросившему. Сам вопрос к слою от этого не меняется — `apply(contours)`, и только.

Цвет называется переменной, а не значением: палитра проекта лежит одним списком в
теме (`assets/css/app.css`), и слой выбирает из неё, а не заводит свои цвета рядом.
Заливка при этом остаётся полупрозрачной — за ней чертёж, который должен читаться
сквозь окраску.
"""

from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from datetime import date, timedelta
from typing import TYPE_CHECKING, Protocol
from urllib.parse import urlencode

from dictionary.models import DictSpaceType
from leases.models import Lease, LeaseSubject

if TYPE_CHECKING:
    from django.contrib.auth.models import AbstractBaseUser

    from .models import Contour, Space


@dataclass(frozen=True)
class Paint:
    """Чем слой заливает контур: цвет, запись в легенде и строка подсказки.

    Подпись в легенде и строка подсказки разные: легенда называет разом все
    помещения одного цвета («Арендопригодные»), а подсказка — то одно, над которым
    стоит указатель.
    """

    #: Договор экрана: этим ключом помечены и контур на плане, и запись легенды.
    key: str
    label: str
    note: str
    colour: str


LEASABLE = Paint(
    key="leasable",
    label="Арендопригодные",
    note="арендопригодное помещение",
    colour="var(--plan-leasable)",
)
COMMON = Paint(
    key="common",
    label="МОП",
    note="место общего пользования",
    colour="var(--plan-common)",
)
TECHNICAL = Paint(
    key="technical",
    label="Технические",
    note="техническое помещение",
    colour="var(--plan-technical)",
)

#: Что типом помещения не является: лестничные клетки, лифтовые шахты и проёмы
#: второго света. Нарисовать их надо — иначе на чертеже остаются необъяснённые
#: провалы, — а залить нечем: любой из трёх цветов назвал бы их тем, чем они не
#: являются. Слой не даёт им ничего: ни заливки, ни записи в легенде, ни подсказки.
OUTSIDE_THE_TYPES = frozenset({DictSpaceType.VOID, DictSpaceType.SHAFT, DictSpaceType.STAIRWELL})

#: За сколько дней до конца договора помещение попадает в «истекает». Переговоры о
#: продлении в коммерческой аренде начинают примерно за квартал: к этому дню решение
#: об аренде уже принимают, а не начинают о нём думать. Срок в 30 дней показывал бы
#: то, о чём договариваться поздно, — и менять это число, не меняя вместе с ним
#: причину, незачем.
RENEWAL_NOTICE_DAYS = 90

VACANT = Paint(
    key="vacant",
    label="Свободно",
    note="свободно: договора на этот день нет",
    colour="var(--plan-vacant)",
)
LEASED = Paint(
    key="leased",
    label="Действует",
    note="договор действует",
    colour="var(--plan-leased)",
)
EXPIRING = Paint(
    key="expiring",
    label="Истекает",
    note=f"договор истекает в течение {RENEWAL_NOTICE_DAYS} дней",
    colour="var(--plan-expiring)",
)


@dataclass(frozen=True)
class PaintedContour:
    """Контур, окрашенный слоем, — то, что рисуется поверх чертежа."""

    space: "Space"
    path_d: str
    #: Чем залит; `None` — контур вне слоя, одна линия без заливки.
    paint: Paint | None


@dataclass(frozen=True)
class Painting:
    """Слой, наложенный на контуры плана: окрашенные контуры и легенда к ним.

    Всё, что экрану нужно знать о слое. Как слой называется, здесь не сказано: имя
    стоит в реестре (`Registration`) — им же слой назван в переключателе, и второе
    имя, лежащее на самой окраске, однажды разошлось бы с первым.
    """

    contours: tuple[PaintedContour, ...]
    legend: tuple[Paint, ...]


class Layer(Protocol):
    """Что экран спрашивает у слоя: наложи себя на контуры этажа.

    Больше он не спрашивает ничего. Одному слою хватает признаков помещения, другому
    нужны дата и договоры, действующие на неё, — и получает он их, когда его собирают,
    а не когда экран его спрашивает. Поэтому «чем залито это помещение» протоколом не
    является: вопрос имеет смысл не для всякого слоя.
    """

    def apply(self, contours: Iterable["Contour"]) -> Painting: ...


def _painting(
    palette: tuple[Paint, ...],
    paint_of: Callable[["Space"], Paint | None],
    contours: Iterable["Contour"],
) -> Painting:
    """Наложить правило на контуры плана — одинаково для всякого слоя.

    Легенда собирается из того, что на этом этаже действительно нарисовано: запись о
    цвете, которого на чертеже нет, была бы подписью к пустому месту. Порядок её —
    порядок палитры: легенда не должна переставляться от того, что на чертеже
    нарисовали первым.

    Правило у каждого слоя своё, а вот это — общее, и держится оно здесь, а не
    повторяется в каждом слое: два списка легенды разъехались бы порядком или тем,
    попадает ли в них незалитый контур.
    """
    painted = tuple(
        PaintedContour(space=contour.space, path_d=contour.path_d, paint=paint_of(contour.space))
        for contour in contours
    )
    drawn = {contour.paint for contour in painted}
    return Painting(
        contours=painted,
        legend=tuple(paint for paint in palette if paint in drawn),
    )


class SpaceTypeLayer:
    """Слой «тип помещения»: помещение сдаётся, является общим или обслуживает здание.

    Единственный слой, который считается по данным, заведённым на всех помещениях, —
    и с ним сотрудник УК судит о сдаваемой площади этажа, а инженер находит ИТП,
    венткамеру и электрощитовую, не читая подписей.

    Тип помещения выводится из двух признаков, а не хранится третьим полем: техническое
    помещение — это ровно то, которое не сдаётся и не является общим. Непроставленный
    признак означает «нет»: «неизвестно» четвёртым цветом рассказывало бы о полноте
    данных, а не о здании. Помещение, помеченное разом сдаваемым и общим, рисуется
    сдаваемым: сданное арендатору общим не бывает.
    """

    #: Порядок легенды. Он же и есть порядок разновидностей.
    palette = (LEASABLE, COMMON, TECHNICAL)

    def _paint_of(self, space: "Space") -> Paint | None:
        """Чем залито помещение или `None`, если оно вне слоя. Дело этого слоя."""
        if space.type in OUTSIDE_THE_TYPES:
            return None
        if space.is_leasable:
            return LEASABLE
        if space.is_common:
            return COMMON
        return TECHNICAL

    def apply(self, contours: Iterable["Contour"]) -> Painting:
        return _painting(self.palette, self._paint_of, contours)


class LeaseTermLayer:
    """Слой «сроки договоров»: свободно, действует, истекает — на названный день.

    Тот же чертёж отвечает на второй вопрос: вакансия видна пространственно, а не
    одним числом, и продление всплывает раньше, чем о нём заговорит арендатор.

    Считается слой на день, а не «сейчас»: «что освобождается к январю» — вопрос,
    который экрану задают адресом, и день приходит от экрана посчитанным (`Screen`).
    Договоры при этом берутся те, что видны спросившему, — тем же чокпоинтом, что и
    всё остальное (ADR 0009): слой не заводит второго места, где решается, чьи данные
    показывать.

    Вне слоя — всё, чего договор не называет: МОП, техническое помещение, шахта,
    лестничная клетка, проём второго света. Срока договора у них не бывает, и заливка
    отвечала бы за них на вопрос, которого им не задавали. Четвёртого цвета для
    «неизвестно» нет и здесь: цвет говорит о здании, а не о полноте данных.
    """

    #: Порядок легенды — он же порядок состояний: пусто, сдано, скоро освободится.
    palette = (VACANT, LEASED, EXPIRING)

    def __init__(self, day: date, leases):
        self.day = day
        self.leases = leases

    def apply(self, contours: Iterable["Contour"]) -> Painting:
        contours = tuple(contours)
        ends = self._ends_of_leases_in_force(contour.space_id for contour in contours)
        return _painting(self.palette, lambda space: self._paint_of(space, ends), contours)

    def _ends_of_leases_in_force(self, space_ids) -> dict:
        """Когда кончается договор, действующий на выбранный день, — по помещениям.

        Одним запросом на весь план: спрашивать про каждый контур отдельно значило бы
        запрос на помещение. Помещения в ответе нет — договора на этот день нет вовсе;
        `None` при нём — открытый конец, то есть «по сей день».

        Договор на помещение в этот день ровно один: периоды по одному помещению не
        пересекаются, и стоит это правило на модели (ADR 0007). Мимо него проходит то
        же, что и мимо правила периодов планов, — `update()`, `bulk_create()` и SQL
        руками; на разъехавшихся так данных полоса окажется произвольной, и чинить их
        придётся тем же способом, каким сломали.
        """
        in_force = (
            LeaseSubject.objects.filter(space_id__in=set(space_ids), lease__in=self.leases)
            .in_force_on(self.day)
            .values_list("space_id", "lease__valid_to")
        )
        return dict(in_force)

    def _paint_of(self, space: "Space", ends: dict) -> Paint | None:
        """Чем залито помещение или `None`, если срока договора у него не бывает.

        Арендопригодность — свойство самого помещения, а не сегодняшнего его
        состояния: пустующий офис остаётся арендопригодным и красится «свободно», а
        венткамера не красится вовсе.
        """
        if space.type in OUTSIDE_THE_TYPES or not space.is_leasable:
            return None
        if space.pk not in ends:
            return VACANT
        ends_on = ends[space.pk]
        if ends_on is None or ends_on > self.day + timedelta(days=RENEWAL_NOTICE_DAYS):
            return LEASED
        return EXPIRING


@dataclass(frozen=True)
class Screen:
    """Экран, спросивший слой: на какой день он смотрит и кому показывает.

    Не запрос: слою не нужны ни путь, ни заголовки, ни метод — нужен день, на который
    считать, и тот, чьи данные показывать. День приходит посчитанным, а не спрошенным
    здесь: берётся он один раз на весь экран, иначе запрос, пришедшийся на полночь,
    посчитал бы слой на один день, а чертёж выбрал бы за другой.
    """

    day: date
    user: "AbstractBaseUser"


@dataclass(frozen=True)
class Registration:
    """Слой в реестре: как он называется и чем он собирается.

    Название стоит здесь, а не на самом слое: им подписан переключатель, и спрашивать
    его пришлось бы у слоя, ещё не собранного, — а собирают слой запросом к базе.

    Признака «считается на день» здесь нет: день принадлежит экрану, а не слою. Счёт
    свободного (#29) считается на выбранный день при любом слое, поэтому называет день
    и предупреждает о выходе за период плана экран, а не тот слой, который сейчас
    показан.
    """

    title: str
    build: Callable[[Screen], Layer]


#: Имя слоя в адресе экрана (`?layer=`) — и то, чем слой из этого адреса делается.
#: Регистрация слоя — строка здесь: экран берёт слой по имени, а какие они бывают,
#: не знает. Собирается слой тем, что ему нужно, из экрана, которым спрошен: типу
#: помещения не нужно ничего, кроме самих контуров, срокам договоров — день, на который
#: смотрит экран, и договоры, видимые спросившему.
LAYERS: dict[str, Registration] = {
    "space-type": Registration(title="Тип помещения", build=lambda screen: SpaceTypeLayer()),
    "lease-term": Registration(
        title="Сроки договоров",
        build=lambda screen: LeaseTermLayer(
            day=screen.day,
            leases=Lease.objects.visible_to(screen.user),
        ),
    ),
}

#: Слой, которым экран открывается. Тип помещения считается по данным, заведённым на
#: всех помещениях: слой, открывающийся пустым, рассказывал бы о полноте данных, а не
#: о здании — на сроках это были бы 44 помещения, покрашенные «свободно» на основании
#: нуля договоров.
DEFAULT_LAYER = "space-type"


@dataclass(frozen=True)
class Choice:
    """Слой в переключателе: как он называется, чем он в адресе и выбран ли он сейчас."""

    name: str
    title: str
    chosen: bool
    #: Хвост адреса экрана, открывающий этот слой: «?layer=lease-term&date=2026-01-01».
    address: str


def _chosen_name(address: Mapping[str, str]) -> str:
    """Имя слоя, названного адресом; неназванный и неизвестный — слой по умолчанию.

    Адрес пересылают и правят руками, поэтому опечатка в имени слоя открывает экран
    со слоем по умолчанию, а не ошибку: сломать экран правкой его адреса не должно
    быть возможно.

    Слой берётся из адреса, а не из памяти о последнем выборе: невидимое состояние
    показывало бы двоим, открывшим «один и тот же экран», разное.
    """
    named = address.get("layer", "")
    return named if named in LAYERS else DEFAULT_LAYER


def chosen_by(address: Mapping[str, str]) -> Registration:
    """Слой, названный адресом экрана, — записью реестра, а не собранным слоем.

    Собирает его экран сам (`Registration.build`), потому что до сборки ему нужно
    спросить у той же записи, считается ли слой на день: два вопроса к одному слою —
    и оба к одной записи, чтобы «который слой показан» имело один ответ.
    """
    return LAYERS[_chosen_name(address)]


def choices(address: Mapping[str, str]) -> tuple[Choice, ...]:
    """Переключатель: все зарегистрированные слои и адрес каждого из них.

    Собирается адрес из нынешнего, а не из одного имени слоя: день, на который
    смотрят, при переключении теряться не должен — «третий этаж, сроки, на 1 января»
    правят слоем, а не переписывают заново.

    Появление слоя в переключателе ничего не стоит: он берётся из того же реестра,
    которым слой назван в адресе, и разойтись эти два списка не могут.
    """
    current = _chosen_name(address)
    # Адрес переписывается по одному значению на имя: `dict(address)` над `QueryDict`
    # оставил бы списки, и в ссылке стояло бы `date=['2026-01-01']`.
    kept = {key: value for key, value in address.items()}
    return tuple(
        Choice(
            name=name,
            title=registration.title,
            chosen=name == current,
            address="?" + urlencode({**kept, "layer": name}),
        )
        for name, registration in LAYERS.items()
    )
