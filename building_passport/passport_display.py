"""Как паспорт здания читается на экране.

Отсутствующее значение пишется «— нет данных» — одним и тем же способом везде, где
поле паспорта пусто: пустое место можно прочитать как ноль, а прочерк нельзя. Правило
живёт здесь, а не в фильтрах шаблона: им пользуется и разметка, и разбор паспорта по
разделам, где по тому же признаку скрывается пустой раздел.
"""

#: Неразрывный пробел: «2 484 м²» не должно переноситься между строк.
NBSP = "\u00a0"

NO_DATA = "— нет данных"


def is_missing(value) -> bool:
    """Значения паспорта нет. Ноль — это значение, а пустая строка — нет."""
    return value is None or value == ""


def or_missing(value):
    """Пустое значение паспорта — «— нет данных»."""
    return NO_DATA if is_missing(value) else value


def space_label(space):
    """Как пространство называется на экране: имя, а при его отсутствии — код.

    Код — учётный идентификатор, но он единственное, чем безымянное помещение
    отличается от соседнего, поэтому подменяет имя вместо прочерка.

    Самого пространства может не быть: у помещения, заведённого без здания, поле
    `building` пусто, и на экране это ровно то же «нет данных», а не поломка.
    """
    if space is None:
        return NO_DATA
    return or_missing(space.name or space.code)


def figure(value):
    """Число до сотых, без округления, неразрывными пробелами и запятой в дробной части.

    Без единицы: ею величину снабжает `measure`, а ставка договора идёт как есть —
    валюты в BCMP нет ни у договора, ни у предмета, и приписанный к числу знак
    утверждал бы то, чего в данных не записано.

    Отсутствующая величина остаётся None: её оформит `or_missing`.
    """
    if is_missing(value):
        return None
    return f"{value:,.2f}".replace(",", NBSP).replace(".", ",")


def measure(value, unit):
    """Величина с единицей — то же число, что и везде, плюс единица измерения."""
    if is_missing(value):
        return None
    return f"{figure(value)}{NBSP}{unit}"


def area(value):
    """Площадь в м² как она записана в паспорте."""
    return measure(value, "м²")


def volume(value):
    """Строительный объём в м³ — та же запись, что и у площадей."""
    return measure(value, "м³")
