"""Как паспорт здания читается на экране.

Отсутствующее значение пишется «— нет данных» — одним и тем же способом везде, где
поле паспорта пусто: пустое место можно прочитать как ноль, а прочерк нельзя. Правило
живёт здесь, а не в фильтрах шаблона: им пользуется и разметка, и разбор паспорта по
разделам, где по тому же признаку скрывается пустой раздел.
"""

#: Неразрывный пробел: «2 484 м²» не должно переноситься между строк.
NBSP = "\u00a0"

NO_DATA = "— нет данных"


def is_missing(value) -> bool:
    """Значения паспорта нет. Ноль — это значение, а пустая строка — нет."""
    return value is None or value == ""


def or_missing(value):
    """Пустое значение паспорта — «— нет данных»."""
    return NO_DATA if is_missing(value) else value


def measure(value, unit):
    """Величина с единицей — до сотых, без округления, неразрывными пробелами.

    Отсутствующая величина остаётся None: её оформит `or_missing`.
    """
    if is_missing(value):
        return None
    return f"{value:,.2f}{NBSP}{unit}".replace(",", NBSP).replace(".", ",")


def area(value):
    """Площадь в м² как она записана в паспорте."""
    return measure(value, "м²")


def volume(value):
    """Строительный объём в м³ — та же запись, что и у площадей."""
    return measure(value, "м³")
