"""Вакансия этажа: сколько арендопригодных помещений свободно и сколько это метров.

«Сколько у нас свободно» — первое, о чём управляющую компанию спрашивают, и экран
этажа отвечает на это словами рядом с чертежом: «свободно 12 из 44 помещений, 387 из
1529 м²». Иначе ответ собирают, считая контуры на плане глазами и складывая площади в
уме, — а посчитанное так никем не проверяется.

Счёт идёт в помещениях **и** в метрах, в отличие от полноты плана
(`plan_completeness`), которая метров не называет. Возражения там были два — площадь
заведена не у всех помещений и масштаба план не объявляет, — и здесь не держится ни
одно: считаются только арендопригодные, площадь у них заведена, а план в этом счёте не
участвует вовсе. Там, где площадь всё-таки не заведена, экран говорит и это
(`unmeasured`): метры, посчитанные не по всем, не должны выглядеть посчитанными по
всем — то же правило, что и «нанесено 47 из 82».

Метры берутся из `Space.area_m2` — обмера самого паспорта — и никогда из договорной
площади предмета: та больше обмера на долю МОП по коэффициенту и является условием
соглашения, а не фактом о здании (ADR 0006). Считай счёт по ней, свободные метры этажа
ездили бы от коэффициента в чужом договоре.

Вложенные арендопригодные считаются независимо: помещение внутри помещения сдаётся
отдельным арендатором и отдельным договором (#25), поэтому и в счёт входит отдельно.
Метры при этом не задваиваются — но не по счастливой случайности, а потому что
арендопригодный родитель, содержащий другое арендопригодное, объединяет соседние в
группу и несёт собственную площадь, свою часть этажа. Содержащие помещения — уборные с
кабинами внутри — арендопригодными не бывают вовсе: они МОП и в счёт не входят ни
числом, ни метром.

Рядом с числом стоит то, на чём оно держится, — сколько договоров под ним. Без этого
пустая база выглядит обмеренным и полностью свободным зданием: «свободно 44 из 44»
читается фактом, хотя означает, что фактов нет ни одного.

Считается всё на названный день (`day`), а не «сейчас»: помещение, чей договор кончается
в декабре, в январе свободно, и спрашивают об этом адресом экрана. На две оси времени
счёт ложится так же, как слой сроков, и второй даты не заводит (ADR 0010).
"""

from collections.abc import Iterable
from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from typing import TYPE_CHECKING

from leases.models import LeaseSubject

if TYPE_CHECKING:
    from .models import Space

ZERO = Decimal("0.00")


@dataclass(frozen=True)
class Vacancy:
    """Сколько свободно, из скольких, в метрах — и на скольких договорах это стоит.

    День лежит здесь же: счёт без дня — половина ответа, и день, названный отдельно
    от числа, однажды разошёлся бы с тем, на который число посчитано.
    """

    #: День, на который счёт посчитан, — тот, что назван адресом экрана.
    day: date
    free_count: int
    #: Знаменатель — арендопригодные, а не все помещения этажа, и потому он не
    #: `space_count`: под планом на том же экране стоит `Completeness.space_count`,
    #: где счёт идёт по всем, и два разных знаменателя под одним именем читались бы
    #: одним.
    leasable_count: int
    free_m2: Decimal
    leasable_m2: Decimal
    #: Сколько договоров действует в этот день на помещения этажа: то, на чём счёт
    #: держится. Ноль означает, что не держится ни на чём.
    lease_count: int
    #: Сколько арендопригодных помещений этажа не обмерено — метры посчитаны без них.
    unmeasured: int


def vacancy_on(day: date, spaces: Iterable["Space"], leases) -> Vacancy:
    """Посчитать вакансию этажа на этот день по этим помещениям и этим договорам.

    Помещения приходят те же, что и в дерево, — уже отобранные чокпоинтом и уже
    собранные по всей глубине этажа: второй обход дерева ради того же набора дал бы
    экрану считать одно, а показывать другое.

    Договоры приходят тем же чокпоинтом (`Lease.objects.visible_to`): счёт не заводит
    второго места, где решается, чьи данные показывать (ADR 0009). Чужой договор,
    оказавшийся на помещении этого этажа, счёт не сдвинет — но и не спрячет от того,
    кто вправе его видеть.
    """
    leasable = [space for space in spaces if space.is_leasable]
    let_spaces, standing_leases = _in_force(day, leasable, leases)
    free = [space for space in leasable if space.pk not in let_spaces]
    return Vacancy(
        day=day,
        free_count=len(free),
        leasable_count=len(leasable),
        free_m2=_measured(free),
        leasable_m2=_measured(leasable),
        lease_count=len(standing_leases),
        unmeasured=sum(1 for space in leasable if space.area_m2 is None),
    )


def _in_force(day: date, leasable: list["Space"], leases) -> tuple[set, set]:
    """Что на этот день сдано и какими договорами — одним запросом на весь этаж.

    Спрашивать про каждое помещение отдельно значило бы запрос на помещение, а этажей
    с сорока помещениями здесь большинство. Форма вопроса та же, что у слоя сроков
    (`plan_layer.LeaseTermLayer._ends_of_leases_in_force`): пересечение периода
    договора с отрезком из одного дня.

    Общего кода у них при этом нет, и это выбор, а не недосмотр. Слою нужен конец
    договора по каждому помещению — им он отличает «действует» от «истекает», — а
    счёту нужны занятые помещения и сами договоры, которых у слоя нет вовсе. Один
    ответ на два вопроса пришлось бы отдавать всем сразу, и каждый вызывающий начал
    бы разбирать чужую половину; правило пересечения при этом всё равно одно и лежит
    там, где ему и место, — на `LeaseSubjectQuerySet.overlapping` (ADR 0007).

    Договоры возвращаются множеством ключей, а не числом строк: один договор называет
    несколько помещений этажа и остаётся при этом одним договором.
    """
    if not leasable:
        return set(), set()
    in_force = (
        LeaseSubject.objects.filter(
            space_id__in={space.pk for space in leasable}, lease__in=leases
        )
        .overlapping(day, day)
        .values_list("space_id", "lease_id")
    )
    let_spaces = {space_id for space_id, _ in in_force}
    standing_leases = {lease_id for _, lease_id in in_force}
    return let_spaces, standing_leases


def _measured(spaces: Iterable["Space"]) -> Decimal:
    """Сумма обмеренных площадей. Необмеренное складывать не с чем, и оно не в счёте.

    Ноль вместо пустой площади здесь не подставляется: он утверждал бы, что помещение
    занимает нисколько, — а сказать надо, что площадь у него не заведена, и говорит
    это `Vacancy.unmeasured`.
    """
    return sum((space.area_m2 for space in spaces if space.area_m2 is not None), ZERO)
