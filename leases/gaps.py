"""Находка полки помещений об арендах: аренда, которая не висит ни на каком договоре.

Полка помещений называет её числом на строке счёта — «аренд без договора: N», третьим после
«свободно N» и «площадь не заведена у M». Пробел этот оставляет сама связь: висеть на
договоре аренда может, но не обязана (ADR 0032), и назвать его больше негде — полка
договоров таких аренд не видит, потому что на ней их нет вовсе. Удаление договора делает
пробел из ниоткуда: аренды переживают его с пустой ссылкой, и четыре отцепленных появляются
здесь (ADR 0034).

Правило раздаётся в той форме, в какой его спрашивают, — тем же приёмом, каким `occupancy`
раздаёт занятость, `contracts/gaps` — находки полки договоров, а `space_kind` — вид
помещения. Форма пока одна: столбец на строке полки. Условия отбора у находки нет, и число
потому ссылкой не становится — в отличие от «свободно N», за которым стоит условие
«свободно»: полка не заявляет отбора, которого не делала (ADR 0014).

Считаются действующие аренды: бумагу заводят той аренде, по которой сегодня сидят, и что
такое «действующая», спрашивается у `occupancy` — второе место, решающее это, однажды
разошлось бы с первым, и строка счёта перестала бы сходиться с колонкой «Арендатор» над ней.

Собственных тестов у модуля нет, как и у `occupancy`: его читает полка, и полка его
проверяет — числом на строке счёта, которое сходится с показанными помещениями.
"""

from django.db.models import Count, OuterRef, Subquery
from django.db.models.expressions import BaseExpression
from django.db.models.functions import Coalesce

from .models import Lease
from .occupancy import in_force_on


def contractless_of_each_room(day) -> dict[str, BaseExpression]:
    """Сколько действующих аренд помещения не называют договора — столбцом на строке полки.

    Одна аннотация, вешаемая на выборку помещений тем именем, каким её читает строка счёта:
    `.annotate(**contractless_of_each_room(день))` и дальше `room.contractless_here`.

    В том же запросе, что и строки, по доводу `tenants_of_each_room`: полка несёт сотни
    строк, и спрошенное у строки спрашивается сотни раз. Считается в арендах, а не в
    помещениях: в одном помещении сидят трое, и бумаги у них три — сказать «помещений без
    договора: 1» значило бы назвать одну работу вместо трёх.

    Своего привратника у аренд здесь нет: аренды помещения видны ровно тогда, когда видно
    оно само (ADR 0018), а строки уже прошли привратник помещений. И дерева правило не
    читает — каждое помещение отвечает за свои аренды и только за свои (ADR 0019).
    """
    here = Lease.objects.filter(space=OuterRef("pk"), contract__isnull=True).filter(
        in_force_on(day)
    )
    return {
        # `values("space").annotate(...)` — это GROUP BY по помещению, так что подзапрос
        # отдаёт одну строку со счётом, а не по строке на аренду. Собственный порядок модели
        # снимается: ORDER BY внутри сгруппированного подзапроса не упорядочивает ничего, а
        # часть баз его и вовсе не принимает.
        "contractless_here": Coalesce(
            Subquery(
                here.order_by()
                .values("space")
                .annotate(leases=Count("pk"))
                .values("leases")
            ),
            0,
        ),
    }
