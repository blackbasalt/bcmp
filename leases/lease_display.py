"""Как договор аренды читается на экране.

Правила показа лежат здесь, а не в фильтрах шаблона, по той же причине, что и правила
паспорта (`passport_display`): ими пользуется не одна разметка. Срок вдобавок называется
в отказе модели, и второе описание того же периода однажды разошлось бы с первым — в
сообщении об отказе стояло бы одно, на экране другое.

Ставки здесь нет: число оформляет `passport_display.figure`, один на весь проект, —
у аренды в нём ничего своего, кроме отсутствующей валюты, о которой там и сказано.
"""


def period(lease):
    """Срок договора: «01.01.2025 — 31.12.2025» или «01.01.2025 — по сей день».

    Пустая дата окончания означает «действует», а не «не действовал никогда», — тот же
    открытый конец, что у периодов планов этажа (ADR 0004, расширенный ADR 0007).
    """
    closes = f"{lease.valid_to:%d.%m.%Y}" if lease.valid_to else "по сей день"
    return f"{lease.valid_from:%d.%m.%Y} — {closes}"


def spaces_counted(count):
    """«2 помещения» — число с существительным при нём, а не цифра в столбце.

    Столбец из голых цифр читается только вместе с заголовком, а строка списка
    пересказывается вслух и пересылается в переписке.
    """
    return f"{count} {_spaces_word(count)}"


def _spaces_word(count):
    """Помещение, помещения, помещений — по последним цифрам числа."""
    if count % 100 in range(11, 15):
        return "помещений"
    if count % 10 == 1:
        return "помещение"
    if count % 10 in (2, 3, 4):
        return "помещения"
    return "помещений"
