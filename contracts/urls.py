from django.urls import path

from . import views

#: Пространство имён — оно же раздел меню: пункт подсвечен на каждом экране, чей `app_name`
#: этот (ADR 0016).
app_name = "contracts"
urlpatterns = [
    # Полка стоит на своём адресе, а не под зданием: расходный договор здания не называет
    # вовсе (ADR 0033), и вход через БЦ спрятал бы четыре вида из пяти.
    path("", views.ContractListView.as_view(), name="contract_list"),
    # Свой адрес у самого договора: обязательство — не рейка на странице про бумагу. Экран
    # документа отвечает «что это за бумага», этот — «какое обязательство и до каких пор»,
    # и каждый ссылается на другой (ADR 0030).
    #
    # Ключ тут ключ документа, потому что договор и есть документ вида «Договор», а не
    # строка рядом с ним: два ключа на одну бумагу дали бы два адреса у одного договора.
    path("<uuid:pk>/", views.ContractDetailView.as_view(), name="contract_detail"),
]
