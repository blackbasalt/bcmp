"""Как один договор читается на своём экране: чем обязательство названо и что под ним стоит.

Собрано здесь, а не в разметке, по той же причине, по какой собраны реквизиты документа и
шапка Стороны: что экран говорит о договоре — это правило о данных, а не о вёрстке. Какие
поля в шапке, в каком порядке их читают и откуда берётся каждое, решается один раз и в
питоне, а шаблону остаётся напечатать готовое. Прочерк за пустым значением сюда не
попадает: его ставит `or_missing`, одним правилом на весь проект.

Собрано здесь то, что договор о себе говорит, а не то, куда с него ведут: строка «Документ» —
ссылка на соседний экран, и стоит она в разметке, как стоят там «Привязки», «Оригинал» и
«Близнец» на странице документа. Адрес — дело разметки, и собранный в питоне он принёс бы
сюда `reverse` ради одной строки.

Порядок шапки — порядок, в котором читают бумагу: как договор называется, по какому номеру
его узнают, что это за договор, на какой он стороне, с кем подписан — и последним то, ради
чего экран и заведён: до каких пор. По алфавиту он не сортируется: экран отвечает на
«какое это обязательство и до каких пор», а у этого вопроса есть порядок.

Здесь же и то, стоит ли на экране блок аренд вовсе. Правило это не своё: его держат условия
договора, и тем же вопросом модель аренды отвергает аренду, повешенную не на ту бумагу
(ADR 0032). Блок стоит ровно там, где аренда вправе появиться, — и это одно правило, а не
два согласных.
"""

from dataclasses import dataclass
from typing import Any

from .contract_display import counterparty_said, ending_said, genus_said, kind_said


@dataclass(frozen=True)
class Field:
    """Строка шапки. Пустое значение остаётся None — прочерк ставит `or_missing`.

    Названа, а не только подписана: разметка несёт имя в `data-field`, так что на поле можно
    указать снаружи, ничего не зная о вёрстке вокруг него.

    Того же вида, что и `Field` на странице документа и на экране Стороны, и написана заново,
    а не взята оттуда: общая у трёх экранов одна лишь форма строки — имя, подпись и значение,
    — и импорт между разделами ради трёх полей первым покажется лишним, когда любой из них
    тронется с места. Тем же доводом в этом проекте написаны дважды и запись даты, и
    согласование числительного.
    """

    name: str
    label: str
    value: Any


def particulars(contract) -> tuple[Field, ...]:
    """Всё, чем договор назван в шапке, готовое к печати.

    Шесть строк, и ни одна не берётся с документа напрямую мимо правил раздела: вид,
    контрагент и «Кончается» написаны теми же словами, какими их печатает строка полки, —
    один договор, два экрана, и разного они говорить не должны.

    Род стоит рядом с видом, а не вместо него: вид — то, что хранится, род — то, что из него
    выводится (ADR 0030), и читатель, видящий оба, видит и правило между ними. На полке рода
    нет, потому что там он был бы колонкой, повторяющей соседнюю; здесь строк шесть, и место
    под вывод есть.

    «Кончается» — тем же словом, каким названа колонка полки, и в тех же трёх состояниях
    (ADR 0031): дата, «бессрочный», «срок не заведён», и приписка о продлении к любому из
    них. Слово «Срок действия», которым та же дата подписана на странице документа, сюда не
    переезжает: там подписана клетка `valid_until`, здесь — ответ о трёх состояниях, и одно
    слово на два разных ответа однажды прочитают в неверном.

    Суммы договора здесь нет и не будет: денежная черта стоит там, где её держат восемь ADR,
    — начисления, оплаты и задолженность живут в учётной системе, и вторая правда о деньгах
    разошлась бы с первой на первом же платеже.
    """
    return (
        Field("title", "Название", contract.title),
        Field("doc_no", "Номер", contract.doc_no),
        Field("kind", "Вид", kind_said(contract)),
        Field("genus", "Род", genus_said(contract)),
        Field("counterparty", "Контрагент", counterparty_said(contract)),
        Field("ending", "Кончается", ending_said(contract)),
    )


def leases_of(contract):
    """Аренды, висящие на этом договоре, — «что входит в договор», спрошенное с его стороны.

    Или ничего вовсе, если это не договор аренды: «не заведено» и «не бывает» — разные
    ответы, и пустой блок сказал бы первое там, где верно второе. У расходного договора блока
    нет вовсе, а не стоит пустым (ADR 0033): всегда пустой раздел научил бы читателя, что у
    договоров эксплуатации бывают аренды, которых никто не завёл, — та же ошибка, из-за
    которой на экране Стороны нет блока «Роли». Тем же `None` отвечает `party_page.contacts_of`
    о физлице, и разметка спрашивает его тем же вопросом.

    Ничего и у договора без вида: аренду на такую бумагу не повесить, и блок не обещает того,
    что будет отвергнуто. А у договора аренды блок стоит и пустым — «аренд не заведено» есть
    ответ об этом договоре и пробел, который кто-то закроет; тем же доводом блок аренды стоит
    на всяком арендопригодном помещении, пустом или нет.

    Вид спрашивается у самих условий, а не сличается здесь с пятёркой: тем же вопросом модель
    аренды отвергает аренду, повешенную не на ту бумагу (ADR 0032), и написанный дважды он
    разошёлся бы молча. Род тут ни при чём: доп услуги — вид доходный, а аренд на нём не
    бывает, потому что клининг, проданный арендатору, помещения не сдаёт.

    Второго привратника здесь нет и не нужно: договор уже прошёл заслон документов
    (ADR 0006), а аренда висит только на договоре той же организации, что и её помещение, —
    это отвергается на модели (ADR 0018). Спросить изоляцию ещё раз значило бы завести второй
    ответ на «чья аренда» рядом с первым.

    Помещение и его БЦ едут в том же запросе: оба названы в строке, а спрошенные разметкой —
    это два запроса на каждую аренду.

    Порядок — свой у самой аренды, новейшая первой: что действует сегодня, спрашивают чаще,
    чем что действовало в 2019-м. Прошлые за складку не прячутся, как на карточке помещения:
    там вопрос «кто здесь сидит сейчас», и сегодняшних надо было отделить, — здесь вопрос
    «что входит в договор», и съехавший арендатор входил в него ровно так же.

    Итога под ними нет и не будет: сложить арендуемые площади значит посчитать дважды
    помещение, стоящее внутри другого, а какое из двух вложений перед нами, по строке не
    видно (ADR 0015, ADR 0019). Число, раздутое на неизвестную величину, хуже отсутствующего,
    потому что его процитируют.
    """
    terms = contract.attached_terms()
    if terms is None or not terms.about_letting_rooms():
        return None
    return contract.leases.select_related("space", "space__building")
