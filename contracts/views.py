from django.contrib.auth.mixins import LoginRequiredMixin
from django.core.exceptions import PermissionDenied
from django.shortcuts import redirect
from django.urls import reverse
from django.utils import timezone
from django.utils.functional import cached_property
from django.views.generic import DetailView, ListView

from bcmp.shelf import also
from documents.models import Document
from parties.models import Org

from . import gaps
from .contract_display import contracts_shown, term_set_aside
from .contract_form import ENTRY, ContractCorrectionForm, ContractEntryForm, carried_back
from .contract_page import leases_of, particulars
from .shelf_search import ShelfSearch


class ContractListView(LoginRequiredMixin, ListView):
    """Раздел «Договоры» — что организация подписала и до каких пор, на одном экране.

    Пятый раздел рядом с «Бизнес-центрами», «Документами», «Помещениями» и «Сторонами»: у
    вопроса «какие у нас обязательства и когда они кончаются» до сих пор не было адреса —
    `Document.valid_until` лежал без единого читателя, а `Lease.contract_no` был свободным
    текстом на восемнадцати вымышленных строках.

    Прежде всего искалка: строка отвечает сама — название, номер, вид, контрагент и
    «Кончается», — а открывать договор незачем, пока не понадобилось большее. Правят и
    удаляют не здесь, а на экране самого договора.

    Створка заведения стоит на этой полке и отправляется на её же адрес: договор заводят
    там, где о договорах читают, и отказ возвращается на экран, с которого форму отправляли
    (ADR 0005). Сотруднику без флага администратора её не показывают вовсе, а заведённый
    договор на полку не возвращается — следом открывается его собственный экран.

    Спрашивают у неё одним вопросом: поиск, вид, род, контрагент, «кончается» и БЦ, да ещё
    два утверждения о самой записи. Вопрос живёт в адресе, поэтому суженная полка — ссылка,
    а «Сбросить» — тот же адрес без него (`shelf_search`).

    И она считает то, чего у неё нет. «Показано 12 из 340 договоров · вид не заведён у 7 ·
    срок не заведён у 4» — тот же приём, что «нанесено 47 из 82» под планом и «площадь не
    заведена у 5» под полкой помещений: пробел здесь не в недостающих строках, а в
    недостающих полях тех строк, что стоят.
    """

    template_name = "contracts/contract_list.html"
    context_object_name = "contracts"

    def get_queryset(self):
        """Данные берутся через заслон документов (ADR 0006) и сужаются после него, а не
        вместо него.

        Порядок двух действий и есть всё дело: чьи это договоры, решено первым и одним
        местом, а спрошенное читателем может лишь убавить строки из этого ответа.
        """
        return self.search.narrow(self.shelf)

    @cached_property
    def shelf(self):
        """Вся полка: каждый договор, который читателю дозволено видеть, до всякого отбора.

        Договор — это документ вида «Договор» (ADR 0030), и других условий тут нет:
        заполненные и незаполненные стоят рядом, потому что сорок сканов попадают на полку
        раньше, чем кому-нибудь проставят вид (ADR 0035), и полка, ждущая заполнения,
        молчала бы ровно о них.

        Условия, контрагент и организация едут в том же запросе, что и строки: спрошенные
        построчно, они были бы тремя запросами на договор при сотнях договоров.

        Порядок — алфавит названий: полку читают глазами, ища на ней договор, а порядок, в
        котором пачка легла в хранилище, не помогает никому. Сроком она не упорядочена
        нарочно — вперёд встали бы договоры, кончившиеся в 2019-м, то есть обязательства,
        которых уже нет; «когда кончается» отвечают колонка и условие отбора, каждое о
        своём. Второй ключ — время загрузки: два договора с одним названием иначе
        встали бы в порядке, который база меняет от запроса к запросу.
        """
        return (
            Document.objects.visible_to(self.request.user)
            .filter(kind=Document.Kind.CONTRACT)
            .select_related("org__party", "terms__counterparty")
            .order_by("title", "created_at")
        )

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)
        # Строки закрепляются здесь, а не остаются запросом: счёт под таблицей и обе находки
        # считаются ровно по тем строкам, которые будут напечатаны. Запрос, спрошенный в
        # разметке заново, был бы вторым чтением базы и вторым случаем разойтись с числом
        # под собой.
        contracts = context["contracts"]
        # Считано, а не спрошено у базы снова: `len` наполняет кэш запроса, из которого
        # потом читает таблица.
        shown = len(contracts)
        # Сколько всего на полке, спрошено один раз и прочитано дважды: это второе число
        # строки счёта, и это же отличает пустую полку от полки, которую опустошил отбор.
        # По отбору этого не прочесть — полку без единого договора спрашивают ровно так же,
        # как полную, — поэтому читается оно с самой полки.
        whole = self.shelf.count()
        context["whole"] = whole
        context["shown"] = contracts_shown(shown, whole)
        # Обе находки — по показанному: число о всей полке под суженной таблицей
        # противоречило бы таблице над собой. Что считать, решает `gaps`, где то же правило
        # написано и для запроса: иначе число под таблицей разошлось бы с таблицей, которую
        # открывает его собственная ссылка.
        context["without_kind"] = sum(
            1 for contract in contracts if gaps.kind_is_unrecorded(contract)
        )
        context["without_term"] = sum(
            1 for contract in contracts if gaps.term_is_unrecorded(contract)
        )
        # И каждая — ссылка: пробел в записи находится с той же полки, одним нажатием, а
        # остальной вопрос остаётся стоять.
        context["without_kind_url"] = self.with_one_more(gaps.NO_KIND)
        context["without_term_url"] = self.with_one_more(gaps.NO_TERM)
        # И то, чего сроковое условие взвесить не смогло, — фразой, а не числами порознь:
        # бессрочный договор и договор с незаведённым сроком в «кончается» не попадают
        # ни один, и
        # молчание об этом прочиталось бы как «таких нет» (ADR 0031). Считается это по всей
        # полке, суженной остальными семью условиями, а не по строкам на экране: строк на
        # экране этих договоров нет — их-то условие и отложило в сторону.
        context["term_set_aside"] = term_set_aside(**self.search.set_aside(self.shelf))
        # Отбор, вернувшийся на экран, с которого его набрали: разметка спрашивает у него,
        # спрашивали ли вообще о чём-нибудь.
        context["search"] = self.search
        # Организация названа тому, кто ведёт больше одного клиента: ему полка общая, и
        # «чей это договор» он спрашивает о каждой строке. Спрошено о читателе, а не о
        # показанном — колонка, зависящая от данных, пропала бы ровно тогда, когда у второго
        # клиента ещё ничего не загружено, а это и есть случай, когда называть надо.
        context["organisation_named"] = Org.objects.handled_by(self.request.user).count() > 1
        # Створка достаётся только тому, кто вправе заводить: действия, которого сотруднику
        # не выполнить, ему и не предлагают — показанная форма, отклоняющая отправку,
        # читается как сломанный экран (ADR 0005). Отказ приносит свою, уже заполненную, так
        # что пустая ставится только на её место.
        if not self.administers_anything:
            context["entry"] = None
        else:
            # Поиск Стороны едет в адресе этой же полки и шлёт с собой всю форму, из неё же
            # форма и собирается обратно — а адрес, поиска не спрашивающий, не заполняет
            # ничего (`carried_back`). Приставка разводит створку с отбором: оба спрашивают и
            # вид, и контрагента, и делят один адрес.
            context.setdefault(
                "entry",
                ContractEntryForm(
                    user=self.request.user,
                    prefix=ENTRY,
                    already_typed=carried_back(self.request.GET, ENTRY),
                ),
            )
        return context

    def post(self, request, *args, **kwargs):
        """Заведение договора: тот же адрес, что и у раздела, — створка стоит на нём.

        Отказ возвращает тот же экран с причиной на форме и набранным в ней, а заведение
        уводит на экран заведённого договора: там дозаполняют то, чего форма не спросила, и
        он же служит подтверждением. Сказать словами было бы нечего — шапка нового экрана
        несёт всё, что отправили.
        """
        if not self.administers_anything:
            # 403, а не 404: раздел этому сотруднику показан, и «его нет» было бы неправдой о
            # том, что уже на экране. Скрывают чужие данные, а не собственную нехватку прав
            # (ADR 0005).
            raise PermissionDenied("Заводить договоры может администратор организации.")
        form = ContractEntryForm(
            request.POST, request.FILES, user=request.user, prefix=ENTRY
        )
        if not form.is_valid():
            self.object_list = self.get_queryset()
            return self.render_to_response(self.get_context_data(entry=form))
        return redirect("contracts:contract_detail", form.save().pk)

    @cached_property
    def administers_anything(self):
        """Ведёт ли этот сотрудник данные хоть какой-нибудь организации (ADR 0005).

        Тот же вопрос, что задаётся на записи: показанная форма и принятый запрос обязаны
        отвечать на него одинаково, иначе экран предлагает то, в чём потом отказывает. Чья
        это будет бумага, решает сама форма — здесь только о том, есть ли створка вообще.
        """
        return Org.objects.administered_by(self.request.user).exists()

    @cached_property
    def today(self):
        """День, о котором говорит экран, взятый один раз на весь запрос.

        Сроковое условие и число отложенного им в сторону — два чтения одного «сегодня», и
        два обращения к часам мгновением врозь могли бы разойтись через полночь: полка
        показала бы строки одной недели, а отложила в сторону по другой.
        """
        return timezone.localdate()

    @cached_property
    def search(self):
        """Что спросили у полки — прочитано один раз и прочитано и строками, и счётом."""
        return ShelfSearch(self.request.GET, user=self.request.user, day=self.today)

    def with_one_more(self, condition):
        """Адрес этого экрана с одним лишним взведённым условием.

        Из чего такая ссылка сложена, решает `bcmp.shelf.also`: число, ставящее условие, —
        устройство полки, а не этого экрана, и полка помещений строит свои ссылки тем же.
        Здесь остаётся единственное, что этому экрану и принадлежит, — адрес, на который
        ссылка возвращается.
        """
        return also(reverse("contracts:contract_list"), self.request.GET, condition)


class ContractDetailView(LoginRequiredMixin, DetailView):
    """Экран одного договора — какое это обязательство и до каких пор.

    Свой адрес и свой экран, а не блок на странице документа: страница документа отвечает
    «что это за бумага» — реквизиты, близнец, связи, скан, — а этот экран отвечает «какое
    обязательство и до каких пор». Вопросы разные, и каждый экран ссылается на другой, как
    карточка БЦ ссылается на свои документы.

    Створка правки стоит здесь же и отправляется на этот же адрес: вид узнают позже скана,
    срок уточняют по допнику, автопролонгацию замечают, перечитывая бумагу, — и правят их
    там, где читают, а отказ возвращается на экран с договором вокруг него (ADR 0005).
    Сотруднику без флага администратора её не показывают вовсе: экран остаётся экраном, а не
    бланком.
    """

    template_name = "contracts/contract_detail.html"
    context_object_name = "contract"

    def get_queryset(self):
        """Договор чужой организации отвечает 404, а не 403, — заслон документов (ADR 0006).

        Ответ не должен подтверждать, что договор существует: отличив «нельзя» от «нет
        такого», читатель узнал бы, с кем работает другой клиент платформы.

        Вид «Договор» сужает наравне с заслоном: у акта обязательства нет, и открывать его
        на этом адресе значило бы показать пустую шапку там, где экран обещает срок.
        """
        return (
            Document.objects.visible_to(self.request.user)
            .filter(kind=Document.Kind.CONTRACT)
            .select_related("terms__counterparty")
        )

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)
        # Шапка приходит в разметку уже собранной: какие поля в ней, в каком порядке их
        # читают и откуда берётся каждое — правило о данных, и решается оно в `contract_page`,
        # а не между тегами.
        context["particulars"] = particulars(self.object)
        # Ничего, а не пустой список, если это не договор аренды: у расходного договора блока
        # аренд нет вовсе, а не стоит пустым (ADR 0033). Решается это в `contract_page`, где
        # написан довод, — и там же, а не здесь, потому что «не заведено» и «не бывает» —
        # разные ответы, и два места, их различающие, однажды ответили бы по-разному.
        context["leases"] = leases_of(self.object)
        # Створка достаётся только тому, кто вправе вести данные этой организации: действия,
        # в котором сотруднику откажут, ему и не предлагают (ADR 0005). Отказ приносит свою,
        # уже заполненную, так что пустая ставится только на её место.
        if not self.administers_the_contract:
            context["edit"] = None
        else:
            # Поиск Стороны едет в адресе самого договора и шлёт с собой всю форму, из неё же
            # форма и собирается обратно — а адрес, поиска не спрашивающий, не заполняет
            # ничего (`carried_back`). Приставки здесь нет: отбора на этом экране не стоит, и
            # разводить имена не с чем.
            context.setdefault(
                "edit",
                ContractCorrectionForm(
                    contract=self.object,
                    user=self.request.user,
                    already_typed=carried_back(self.request.GET),
                ),
            )
        return context

    def post(self, request, *args, **kwargs):
        """Правка условий: тот же адрес, что и у экрана, — створка стоит на нём.

        Отказ возвращает тот же экран с причиной на форме и набранным в ней, а сохранённое
        подтверждается перезагруженным экраном: все пять условий стоят в его шапке, и сказать
        о правке словами было бы нечего.
        """
        self.object = self.get_object()
        if not self.administers_the_contract:
            # 403, а не 404: раздел этому сотруднику уже показали, и отвечать «этого нет»
            # значило бы солгать о показанном. Чужой договор отвечает 404 выше, и отвечает им
            # записи по той же причине, по какой чтению (ADR 0005, ADR 0006).
            raise PermissionDenied("Вести условия договора может администратор организации.")
        form = ContractCorrectionForm(request.POST, contract=self.object, user=request.user)
        if not form.is_valid():
            return self.render_to_response(self.get_context_data(edit=form))
        form.save()
        return redirect("contracts:contract_detail", self.object.pk)

    @cached_property
    def administers_the_contract(self):
        """Ведёт ли этот сотрудник данные организации этого договора (ADR 0005).

        Не «ведёт ли он хоть что-нибудь»: право принадлежит паре «сотрудник + организация», и
        вопрос пошире отдал бы администратору одного клиента створку над бумагой другого.
        Организацию называет сам договор — спрашивать её у формы здесь нечего.
        """
        return (
            Org.objects.administered_by(self.request.user)
            .filter(pk=self.object.org_id)
            .exists()
        )
