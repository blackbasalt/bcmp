"""Что спрашивают у полки договоров — восемь условий одним вопросом.

Шесть из них о самом договоре: текст, который надо найти, вид, род, контрагент, «кончается»
и БЦ. Ещё два — о записи о нём, а не о нём самом: «вид не заведён» и «срок не заведён». Все
восемь стоят одной формой, потому что полка сужается одним вопросом — «расходные договоры
с ТОО «Альфа», кончающиеся в этом месяце», — и отвеченные по одному они оставили бы экрану
самому решать, как их сложить.

Условия живут в адресе, а не в отправке: суженная полка перезагружается, живёт во вкладке и
отправляется коллеге — и сброс отбора есть адрес без него, то есть сама полка.

Поиск достаёт до названия и номера и не дальше. Слово, набранное ради одной бумаги, не
должно отвечать всеми, у кого тот же контрагент: у контрагента есть своё условие, и
спрашивают его, когда его имеют в виду. BCMP не читает документ внутри, а близнец
существует для ИИ-управляющего и здесь не индексируется (ADR 0007).

**Род нигде не хранится** и сужает полку тем же `STANDS_ON`, каким шапка договора называет
его словом (`genus`): иначе полка нашлась бы одним чтением, а строка напечатала бы другое.

**«Кончается» знает три значения и ни одного свободного числа дней** — свободное пригласило
бы ввести 0 и 3650. Что каждое из трёх значит, решает `bcmp.windows`, а не этот раздел: теми
же словами спрашивает полка Сторон — «кого поздравить на этой неделе», — и «на этой неделе»
обязано кончаться в одно и то же воскресенье на обеих. Бессрочные договоры и те, которым
срока не заводили, в это условие не попадают вовсе: конца срока у них нет, и взвесить их
вопросом «когда кончается» нечем. Названы они числом на строке счёта — `set_aside` ниже, —
чтобы отбор не заявлял, будто взвесил то, чего не смог прочесть (ADR 0031).

**«БЦ» сужает полку до одного вида — «Аренда помещений».** Такой договор достаёт до БЦ через
свои аренды и их помещения, а эксплуатация, капитальные работы и поставка ТМЦ к зданию не
привязываются вовсе (ADR 0033). Выпадение расходных здесь — честный ответ, а не пробел, и
экран говорит об этом словами: молча полка выглядела бы потерявшей четыре вида из пяти.
Назван вид, а не «договоры аренды», которыми пишет сам ADR: словарь держит «договор аренды»
в списке того, чем не называют аренду (CONTEXT.md, «Аренда»), а на этом экране рядом стоят и
список видов, и раздел про сами аренды.

Каждое условие проверяется до того, как его применят, и не прочитавшееся сужает полку до
нуля, а не отбрасывается (ADR 0014), — это делает `bcmp.shelf`, а не эта полка; ею же
читается, спрашивали ли вообще о чём-нибудь. Какой из двух пустых экранов показать, решает
не она и не по этому чтению, а по размеру несуженной полки (`ContractListView`); чтение
спрашивается здесь только ради того, есть ли что предлагать «Сбросить».
"""

from django import forms
from django.core.exceptions import ImproperlyConfigured
from django.db.models import Q

from bcmp import shelf, windows
from building_passport.models import Space
from documents.building_choice import BuildingChoice
from documents.models import ContractTerms, Document

# Ищут здесь ровно то же и ровно там же, где полка документов: название и номер одной и той
# же строки одной и той же таблицы. Поэтому условие берётся у неё, а не пишется заново, — тем
# же доводом, каким `contract_display` берёт у того же раздела написание даты: два описания
# одного поиска разошлись бы, и один номер находился бы на одной полке и не находился на
# другой. С `parties` и `rooms` общего у него только грамматика запроса — там другие поля
# другой таблицы, — и с ними оно нарочно порознь.
from documents.shelf_search import matching
from leases.models import Lease
from parties.models import Party

from . import gaps, genus

#: Имя срокового условия в адресе. Написано здесь по той же причине, по какой `gaps` держит
#: имена своих двух: его читает и сама форма, и строка счёта, спрашивающая, что это условие
#: взвесить не смогло.
ENDING = "ending"

#: Роды, как они стоят в списке отбора: пустой выбор и оба из `genus`. Собран здесь, а не в
#: теле класса, потому что поле с этим же именем там и объявляется, — а взяты роды всё равно
#: из одного `genus.GENERA`, чтобы список отбора и подпись в шапке договора не разошлись.
GENERA_OFFERED = [("", "Любой род"), *genus.GENERA]


def ending_within(window: str, day) -> Q:
    """Договоры, чей срок кончается не позже конца окна и не раньше дня, о котором спросили.

    Окно — «отсюда и до»: «кончается» спрашивают о том, что ещё предстоит, и обязательство,
    истёкшее в понедельник, в среду уже кончилось, а не кончается. Что такое конец окна,
    считает `bcmp.windows` — одно чтение календаря на две полки.

    Бессрочные договоры и те, которым срока не заводили, выпадают сами: конца срока у них
    нет, а `NULL` не
    сравнивается ни с одной датой. Заведённая дата при этом перевешивает взведённую
    бессрочность, ровно как в строке под «Кончается»: спорящие условия полка разрешает
    одинаково, где бы их ни читала.
    """
    return Q(valid_until__gte=day, valid_until__lte=windows.ends_on(window, day))


def standing_in(building) -> Q:
    """Договоры, чьи аренды сидят в этом БЦ, — единственный путь договора к зданию.

    Через аренды и их помещения, а не через привязку документа: расходный договор здания не
    называет вовсе (ADR 0033), и `DocumentLink` с `entity_type="space"`, лежащий рядом и
    рабочий, здесь сознательно не используется.

    Ключами, а не соединением: договор, у которого в одном БЦ сидят два арендатора, при
    соединении встал бы на полку дважды — и сбил бы не только таблицу, но и счёт под ней.
    """
    return Q(pk__in=Lease.objects.filter(space__building=building).values("contract_id"))


def counterparties_of(user):
    """Стороны, с которыми у читателя есть хоть один договор, — список условия «Контрагент».

    Свои договоры и только они (ADR 0006). Весь реестр в 699 строк был бы не выбором, а
    прокруткой, и назвал бы вдобавок Стороны, с которыми не подписано ничего: условие,
    способное ответить только «ничего не нашлось», учит читателя, что полоса врёт. А чужой
    контрагент в списке сказал бы, с кем работает другой клиент платформы.
    """
    return (
        Party.objects.filter(
            contracts__document__in=Document.objects.visible_to(user).filter(
                kind=Document.Kind.CONTRACT
            )
        )
        .distinct()
        .order_by("name")
    )


class ShelfSearch(shelf.Search):
    """Отбор, как о нём спросили: что найти, какого вида и рода, с кем, до каких пор и где.

    Одной формой на все восемь условий, а не по форме на условие. Это один вопрос —
    «расходные договоры с ТОО «Альфа», кончающиеся в этом месяце», — и отвеченный по одному
    он оставил бы экрану самому решать, как восемь складываются.

    Связывается она всегда, даже с пустым адресом: полка, у которой ничего не спрашивали, —
    это отбор без единого заполненного условия, и несвязанная форма потребовала бы второго
    способа сказать «не спрашивали ничего».
    """

    q = forms.CharField(
        required=False,
        label="Поиск",
        # Сказано на поле, потому что само поле этого сказать не может: пустая строка не
        # намекает, что в ней ищется и номер, — а номер как раз и есть то, что читатель
        # держит перед глазами, читая его со счёта.
        widget=forms.TextInput(attrs={"placeholder": "Название или номер"}),
    )
    kind = forms.ChoiceField(
        required=False,
        label="Вид",
        # Пустой выбор — обычное состояние условия, и он так и назван: «Любой вид» — это
        # ответ, а «---------» — дыра в списке.
        choices=[("", "Любой вид"), *ContractTerms.Kind.choices],
        # Нечитаемое условие сужает полку до нуля, и экран обязан сказать почему. Оставленный
        # Django, отказ сообщил бы «Выберите корректный вариант» о списке, которого читатель
        # не трогал: значение пришло из адреса, а список всё это время стоит на «Любой вид».
        error_messages={"invalid_choice": "В адресе указан вид, которого нет в списке."},
    )
    genus = forms.ChoiceField(
        required=False,
        label="Род",
        # Доходные и расходные врозь, не перечисляя виды по одному. Роды берутся из `genus`
        # одним списком: род, названный в шапке договора, и род, которым сузили полку, —
        # одно и то же слово и одна и та же сторона.
        choices=GENERA_OFFERED,
        error_messages={"invalid_choice": "В адресе указан род, которого нет в списке."},
    )
    counterparty = forms.ModelChoiceField(
        # Набор задаётся в `__init__`: он зависит от того, кто спрашивает, а поле,
        # объявленное на классе, этого ещё не знает.
        queryset=Party.objects.none(),
        required=False,
        label="Контрагент",
        empty_label="Любой контрагент",
        # Одно написание на оба чтения нечитаемого контрагента: Сторона, которой нет вовсе,
        # и Сторона, с которой договор есть у другого клиента, отвечают одинаково — сказать
        # их врозь значило бы сказать читателю, с кем работает тот клиент (ADR 0006).
        error_messages={
            "invalid_choice": "В адресе указан контрагент, которого нет в списке."
        },
    )
    ending = forms.ChoiceField(
        required=False,
        # «Кончается» — то же слово, каким названа колонка, о которой условие спрашивает:
        # читатель сужает полку тем самым, что читает в строке.
        label="Кончается",
        # Три значения и ни одного свободного числа дней. Что каждое из трёх значит, говорит
        # `bcmp.windows`, а не этот раздел: теми же тремя словами спрашивает полка Сторон, и
        # «на этой неделе» не должно кончаться здесь воскресеньем, а там следующей средой.
        choices=[("", "Когда угодно"), *windows.WINDOWS],
        # Отказ назван так, чтобы он же и отвечал набравшему `?ending=120`: полка не знает
        # свободного числа дней, и узнать об этом лучше здесь, чем не узнать вовсе.
        error_messages={
            "invalid_choice": (
                "В адресе указан срок, которого нет в списке: "
                "«кончается» знает три значения."
            )
        },
    )
    building = BuildingChoice(
        queryset=Space.objects.none(),
        required=False,
        label="БЦ",
        empty_label="Любой БЦ",
        # Одно написание на оба чтения нечитаемого БЦ: здания, которого нет, и здания
        # другого клиента — один ответ, потому что сказать их врозь значило бы сказать этому
        # читателю, что есть у того (ADR 0006).
        error_messages={"invalid_choice": "В адресе указан БЦ, которого нет в списке."},
    )
    no_kind = forms.BooleanField(
        required=False,
        label="Вид не заведён",
        # Не четвёртым значением в списке видов: видов пять и ровно пять, а это утверждение
        # о записи, а не о договоре. Ровно тем же доводом стоит `no_kind` на полке
        # помещений.
    )
    no_term = forms.BooleanField(
        required=False,
        label="Срок не заведён",
        # Своё условие, а не дыра в сроковом: «кончается в ближайшие 90 дней» не найдёт
        # договор, которому конца не заводили, и молча это прочтётся как «таких нет», тогда
        # как правда — «мы не знаем» (ADR 0031).
    )

    def __init__(self, data, *, user, day, **kwargs):
        # Связывается всегда, даже с пустым адресом, — по причине, названной в докстроке
        # класса.
        super().__init__(data, **kwargs)
        # День, о котором говорит сроковое условие, передан, а не взят у часов здесь: что
        # такое «сегодня», экран решает один раз и говорит почему (`ContractListView.today`).
        self.day = day
        # БЦ предлагаются свои (ADR 0001), и контрагенты тоже: чужое здание и чужая Сторона
        # в списке назвали бы, с кем и где работает другой клиент платформы.
        self.fields["building"].offer(Space.objects.buildings_visible_to(user))
        self.fields["counterparty"].queryset = counterparties_of(user)

    def answering(self, contracts):
        """Договоры, отвечающие отбору, из тех, что читателю и так видны.

        Какие договоры сюда вообще доходят — чьи они — решено заслоном до вызова `narrow`
        (ADR 0006); условия могут только убавить строки из этого ответа.

        Сроковое условие стоит последним и отдельно от семи остальных, потому что о нём
        спрашивают дважды: раз — какие строки оно оставило, раз — сколько оставили бы семь
        без него. Ответ от порядка не зависит: условия только убавляют строки, в каком бы
        порядке их ни ставили.
        """
        contracts = self._apart_from_the_term(contracts)
        if window := self.cleaned_data[ENDING]:
            contracts = contracts.filter(ending_within(window, self.day))
        return contracts

    def _apart_from_the_term(self, contracts):
        """Семь условий из восьми — весь отбор, кроме срокового.

        Отдельным шагом, а не ключом «применять ли срок» у `answering`: подпись `answering`
        общая на все четыре полки (`bcmp.shelf`), и ключ, нужный одной из них, расширил бы
        её для всех. Перечислить же семь условий второй раз значило бы завести второе место,
        где о новом условии придётся вспомнить, с одним из двух забытым.
        """
        asked = self.cleaned_data
        if text := asked["q"]:
            contracts = contracts.filter(matching(text))
        if kind := asked["kind"]:
            contracts = contracts.filter(terms__kind=kind)
        # `genus` здесь — модуль, а не поле формы: имена методов не видят пространства имён
        # класса, и правило о родах берётся оттуда же, откуда его берёт шапка договора.
        if stands_on := asked["genus"]:
            contracts = contracts.filter(genus.being(stands_on))
        if counterparty := asked["counterparty"]:
            contracts = contracts.filter(terms__counterparty=counterparty)
        if building := asked["building"]:
            contracts = contracts.filter(standing_in(building))
        if asked[gaps.NO_KIND]:
            contracts = contracts.filter(gaps.kind_unrecorded())
        if asked[gaps.NO_TERM]:
            contracts = contracts.filter(gaps.term_unrecorded())
        return contracts

    def set_aside(self, contracts) -> dict[str, int]:
        """Сколько договоров сроковое условие взвесить не смогло, по двум состояниям срока.

        Отбор не заявляет, будто взвесил то, чего не смог прочесть (ADR 0031): «кончается в
        ближайшие 90 дней» бессрочных не показывает и незаведённых не показывает тоже, и
        молчание об этом читалось бы как «таких нет».

        Считается по остальным семи условиям, а не по всей полке: спросивший о договорах
        эксплуатации имеет в виду их, и число, набранное со всех пяти видов, отвечало бы не
        на его вопрос.

        Ноль и ноль, пока о сроке не спрашивали: полка, у которой сроковое условие не
        задавали, ничего в сторону и не откладывала. Нечитаемый отбор — тоже ноль и ноль:
        полка под ним пуста целиком, и объяснять её содержимым было бы вторым ответом на
        то, о чём экран уже сказал словами.

        Именами, а не парой чисел по порядку: числа тут однородны, и переставленные местами
        они поменяли бы местами слова при них, не уронив ничего.
        """
        if not self.is_valid() or not self.cleaned_data[ENDING]:
            return {"perpetual": 0, "unrecorded": 0}
        weighed = self._apart_from_the_term(contracts)
        return {
            "perpetual": weighed.filter(gaps.term_perpetual()).count(),
            "unrecorded": weighed.filter(gaps.term_unrecorded()).count(),
        }


#: Условия, названные в `gaps` и в `ENDING`, но не объявленные полем, — и таких не бывает.
#:
#: Проверено на запуске, а не тестом, тем же приёмом, каким `genus` проверяет расстановку
#: видов: `gaps` обещает, что имя условия написано один раз, а переименованное поле оставило
#: бы обещание в силе и молча — `cleaned_data` поднял бы `KeyError` на первой же полке, а
#: ссылка под таблицей вела бы на условие, которого форма не читает. `raise`, а не `assert`:
#: отказ, снимаемый ключом запуска, — это отказ, которого в одном из запусков нет.
_UNDECLARED = {gaps.NO_KIND, gaps.NO_TERM, ENDING} - set(ShelfSearch.base_fields)
if _UNDECLARED:
    raise ImproperlyConfigured(
        "Находка полки договоров называется условием отбора, и имя у них одно. Не объявлены "
        "полями: " + ", ".join(sorted(_UNDECLARED)) + " — допишите их в ShelfSearch."
    )
