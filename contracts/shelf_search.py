"""Что спрашивают у полки договоров — пока только две находки, которые она сама называет.

Отбор полки — поиск, вид, род, контрагент, «кончается» и БЦ — приходит своим тикетом, и
полосы над таблицей тут ещё нет. Но два условия стоят уже сейчас, потому что без них строка
счёта лгала бы: «вид не заведён у 12» — число-ссылка, а ссылка, никуда не ведущая, называет
работу и не даёт к ней перейти. Эти два условия и есть та работа, названная адресом.

Условия живут в адресе, а не в отправке: суженная полка перезагружается, живёт во вкладке и
отправляется коллеге — и сброс отбора есть адрес без него, то есть сама полка.

Нечитаемое условие сужает полку до нуля, а не отбрасывается (ADR 0014), — и это делает
`bcmp.shelf`, а не эта полка; ею же читается, спрашивали ли вообще о чём-нибудь.
"""

from django import forms
from django.core.exceptions import ImproperlyConfigured

from bcmp import shelf

from . import gaps


class ShelfSearch(shelf.Search):
    """Отбор, как о нём спросили: два утверждения о самой записи и ни одного о договоре.

    Одной формой, а не двумя полями порознь: полка сужается одним вопросом, и обе находки —
    его части. Остальные части придут сюда же, когда придёт полоса отбора.

    Связывается она всегда, даже с пустым адресом: полка, у которой ничего не спрашивали, —
    это отбор без единого заполненного условия, и несвязанная форма потребовала бы второго
    способа сказать «не спрашивали ничего».
    """

    no_kind = forms.BooleanField(
        required=False,
        label="Вид не заведён",
        # Не четвёртым значением в списке видов: видов пять и ровно пять, а это утверждение
        # о записи, а не о договоре. Ровно тем же доводом стоит `no_kind` на полке
        # помещений.
    )
    no_term = forms.BooleanField(
        required=False,
        label="Срок не заведён",
        # Своё условие, а не дыра в сроковом: «кончается в ближайшие 90 дней» не найдёт
        # договор, которому конца не заводили, и молча это прочтётся как «таких нет», тогда
        # как правда — «мы не знаем» (ADR 0031).
    )

    def answering(self, contracts):
        """Договоры, отвечающие отбору, из тех, что читателю и так видны.

        Какие договоры сюда вообще доходят — чьи они — решено заслоном до вызова `narrow`
        (ADR 0006); условия могут только убавить строки из этого ответа.
        """
        asked = self.cleaned_data
        if asked[gaps.NO_KIND]:
            contracts = contracts.filter(gaps.kind_unrecorded())
        if asked[gaps.NO_TERM]:
            contracts = contracts.filter(gaps.term_unrecorded())
        return contracts


#: Условия, названные в `gaps`, но не объявленные полем, — и таких не бывает.
#:
#: Проверено на запуске, а не тестом, тем же приёмом, каким `genus` проверяет расстановку
#: видов: `gaps` обещает, что имя условия написано один раз, а переименованное поле оставило
#: бы обещание в силе и молча — `cleaned_data` поднял бы `KeyError` на первой же полке, а
#: ссылка под таблицей вела бы на условие, которого форма не читает. `raise`, а не `assert`:
#: отказ, снимаемый ключом запуска, — это отказ, которого в одном из запусков нет.
_UNDECLARED = {gaps.NO_KIND, gaps.NO_TERM} - set(ShelfSearch.base_fields)
if _UNDECLARED:
    raise ImproperlyConfigured(
        "Находка полки договоров называется условием отбора, и имя у них одно. Не объявлены "
        "полями: " + ", ".join(sorted(_UNDECLARED)) + " — допишите их в ShelfSearch."
    )
