"""Формы договора — то, чем администратор организации заменяет Django admin.

Две формы и одна половина на двоих. **Заведение** стоит на полке и спрашивает бумагу и
обязательство разом — название, номер, дату, срок, скан, контрагента, вид, бессрочность и
автопролонгацию: новый договор с поставщиком не должен требовать админки. **Правка** стоит
на экране договора и спрашивает одни условия: вид узнают позже скана, срок уточняют по
допнику, автопролонгацию замечают, перечитывая бумагу.

Одним модулем и наследованием, а не двумя списками полей: условия у них одни и те же, и
разошедшись, они дали бы одному договору два набора условий — заведённый одной формой
оказался бы неправимым другой. Тем же доводом форма аренды одна на заведение и на правку.
Различает их не набор условий, а то, что вокруг: у заведения есть бумага и организация, у
правки — договор, который уже есть.

**Обязательно одно название.** Всё остальное оставлено пустым нарочно, а не по недосмотру:
договор обогащается со временем, и форма, требующая всего сразу, держала бы известный номер
снаружи, пока ищут дату. Вид пустует наравне с прочим и это обычное состояние, а не пробел в
проверке (ADR 0035). Название же обязательно потому, что полку читают по названиям, и строка
без него не находится ничем.

**Бессрочность и дата конца отвергаются вместе.** Состояний срока три — дата, бессрочный, не
заведён, — и два разом не бывает (ADR 0031). Отказ стоит на форме, а не на модели, и это
решение, а не забывчивость: `contract_display.ending_said` и `gaps.term_perpetual` спор
разрешают при чтении, потому что прочесть такую строку полке всё равно придётся — её заводят
в админке Django, — и написано там прямо, что ни одна форма её не заводит. Здесь это
обещание и держат. Вторая его половина стоит в `documents/document_edit.py`: «Срок действия»
правят и на странице документа, и дверь, оставленная открытой, завела бы тот же спор с
другой стороны.

**Контрагента выбирают из Сторон своей учётной карточки.** «С кем мы подписали» — вопрос о
знании, а не о существовании, и отвечает на него полка Сторон (ADR 0020). Набор берётся у
формы документа, а не собирается здесь заново: «кем выдан» сужен ровно тем же вопросом, и
второй ответ на него разошёлся бы с первым в тот день, когда один из двух чему-нибудь
научится. Что отличается — из чего выбирают — остаётся за формой, как `party_choice` и
говорит; здесь это то же самое, поэтому и взято оттуда.

**Сторону этой формой не заводят.** Не нашлось — идут в раздел «Стороны»: реестр, пополняемый
из створки договора, зарос бы «ТОО Альфа», «Альфа ТОО» и «ТОО «Альфа»» — тремя написаниями
одной компании, и ни один экран не сказал бы, которую из них договор имеет в виду.
"""

