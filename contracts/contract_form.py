#: Под каким именем поиск Стороны едет в адресе. Ничем иным адрес форму не заполняет, и это
#: то, что так говорит.
SEARCH = "counterparty_q"

#: Приставка, которой створка заведения метит свои поля. Полка уже спрашивает у адреса и вид,
#: и контрагента — своим отбором, — и два вопроса, делящие одно имя, отвечали бы друг за
#: друга: суженная до эксплуатации полка проставляла бы вид новому договору. У экрана договора
#: отбора нет, и приставки там нет тоже — она развела бы то, что и так порознь.
ENTRY = "entry"


def carried_back(address, prefix="") -> dict:
    """Что адрес возвращает в форму — и ничего вовсе, пока он не спрашивает поиска.

    Поиск шлёт с собой всю форму, как она стоит, и форма собирается обратно из неё же: в
    ответе перерисовывается одна створка контрагента, и выбранная в ней Сторона обязана
    остаться выбранной. Возвращается при этом всё, а не два поля: форма одна, и собранная из
    половины адреса она отвечала бы о себе не то, чем была.

    Адрес, поиска не спрашивающий, не заполняет ничего, и в этом весь смысл гейта:
    `…/contracts/?entry-title=Договор` иначе открыл бы форму с названием, которого никто не
    набирал, а проставленное поле сохраняют, не взглянув, — ровно то, чего не делает загрузка
    плана (ADR 0004). Форму заполняет тот, кто заводит договор, а не тот, кто прислал ссылку.

    Третий такой же гейт в проекте, и все три порознь: у аренды имён поиска два, у документа
    одно, здесь одно, но под приставкой. Довод же у них общий и переписан будет тоже один раз
    — это решение ADR 0004, а не решение формы.
    """
    head = f"{prefix}-" if prefix else ""
    if not address.get(f"{head}{SEARCH}"):
        return {}
    return {
        name.removeprefix(head): value
        for name, value in address.dict().items()
        if name.startswith(head)
    }


def recorded(contract) -> dict:
    """Условия договора, как они стоят сейчас, — то, чем открывается форма правки.

    Срок берётся с самого документа, остальное — из условий рядом с ним: договор — это
    документ вида «Договор» с таблицей условий сбоку (ADR 0030), и форма, спрашивающая обе
    половины, обе половины и показывает.

    Форма, поднявшаяся забывшей заведённое, сохранила бы его прочь: пришедший поправить вид
    не должен терять контрагента и срок — тот же довод, по которому правка аренды поднимается
    с арендой в полях.
    """
    terms = contract.attached_terms()
    return {
        "counterparty": terms.counterparty_id,
        "kind": terms.kind or "",
        "valid_until": contract.valid_until,
        "is_perpetual": terms.is_perpetual,
        "auto_prolongs": terms.auto_prolongs,
    }


class ContractTermsForm(forms.Form):
    """Общая половина двух створок: условия договора и его срок, как их спрашивают обе.

    Сама по себе не ставится ни на один экран — ставят её потомков, — и нужна она затем,
    чтобы вопрос об условиях был задан один раз: заведение и правка спрашивают одно и то же,
    и два списка полей разошлись бы на первом же новом условии.

    Формой модели она не является, и не может ею быть: срок живёт на документе, а остальные
    четыре условия — в строке рядом с ним, и одна форма пишет в обе таблицы. Зато вопрос она
    задаёт один — «какое это обязательство и до каких пор», — а разложить ответ по двум
    таблицам дешевле, чем разложить вопрос по двум формам.
    """

    #: Сторона ищется, а не пролистывается: в реестре 699 строк, по большей части поставщики, и
    #: суженный до учётных карточек читателя он всё ещё сотни. Что можно выбрать, задаёт
    #: `queryset`, а что предложено — `offer`; почему это два разных набора, сказано в
    #: `PartyChoice`.
    counterparty = PartyChoice(
        queryset=Party.objects.none(),
        required=False,
        label="Контрагент",
        # Одни слова на оба чтения непринятого ключа: такой Стороны нет вовсе или её нет на
        # полке этой организации. Различить их значило бы сказать читателю, что есть у другого
        # клиента (ADR 0006).
        error_messages={
            "invalid_choice": "Такой Стороны среди ваших нет — "
            "контрагента выбирают из раздела «Стороны»."
        },
    )
    #: Сам поиск — в форме, а не рядом с ней: он едет параметром в адресе на GET и обратно в
    #: отправке на POST, так что отказ перерисовывает тот же список, из которого Сторону
    #: выбрали, и выбора читателю не стоит.
    counterparty_q = forms.CharField(required=False, label="Найти Сторону")
    kind = forms.ChoiceField(
        required=False,
        label="Вид договора",
        # Пустой выбор — обычное состояние договора, и он так и назван: «вид не заведён» —
        # ответ, теми же словами, какими его называет строка счёта под полкой, а «---------»
        # — дыра в списке. Виды берутся у модели: тем же словом вид назван в строке полки и
        # в шапке экрана.
        choices=[("", "Вид не заведён"), *ContractTerms.Kind.choices],
        # Ключ, пришедший из отправки, а не из списка: Django сказал бы «Выберите корректный
        # вариант» о списке, которого читатель не трогал.
        error_messages={"invalid_choice": "Такого вида договора нет: их пять, и все в списке."},
    )
    valid_until = forms.DateField(
        required=False,
        # «Кончается» — то же слово, каким названа колонка полки и строка шапки: один договор,
        # три экрана, и разного они говорить не должны. «Срок действия», которым та же дата
        # подписана на странице документа, сюда не переезжает — там подписана клетка, здесь
        # ответ о трёх состояниях.
        label="Кончается",
        widget=DateEntered(),
    )
    is_perpetual = forms.BooleanField(
        required=False,
        label="Бессрочный",
        help_text="Конца срока нет по самому соглашению — это не то же, что «срок не заведён».",
    )
    auto_prolongs = forms.BooleanField(
        required=False,
        label="Продлевается автоматически",
        help_text="Продлевается сам, пока ни одна сторона не заявила обратного.",
    )

    def __init__(self, data=None, files=None, *, user, already_typed=None, **kwargs):
        """Кто читает — из запроса, что уже набрано — из адреса, остальное — из договора.

        `already_typed` — то, что стояло в полях, когда отправили поиск. Кладётся начальным
        значением, а не связывается данными: никто ничего не отправлял, и форма, ответившая
        на поиск отказами, отказала бы в вопросе, которого не задавали.

        Оно же и вытесняет заведённое целиком, а не пополняет его: `hx-include` шлёт с
        поиском всю форму, так что снятая галочка приезжает отсутствием имени — и наложенная
        на заведённое, она вернулась бы взведённой.
        """
        super().__init__(data, files, initial=already_typed or self.standing(), **kwargs)
        counterparty = self.fields["counterparty"]
        counterparty.queryset = known_to(user, kept=self.kept)
        standing = list(found_among(counterparty.queryset, self.asked(SEARCH)))
        #: Нашлось ли что-нибудь — вопрос о поиске, а не о длине списка: уже проставленная
        #: Сторона стоит в списке и тогда, когда поиск не нашёл никого, и «не нашлось» должно
        #: сказаться и над ней.
        self.nothing_found = bool((self.asked(SEARCH) or "").strip()) and not standing
        # Выбранное едет с поиском и возвращается с ним: уже проставленная Сторона стоит в
        # списке и тогда, когда поиск не нашёл никого, — иначе искавший зря сохранил бы
        # пустоту на её месте.
        counterparty.offer(standing, chosen=self.asked("counterparty"))

    #: Контрагент, уже стоящий на договоре. Он в наборе, что бы ни говорили учётные карточки:
    #: 62 Стороны пришли без чьей-либо карточки, и сузить их прочь значило бы стереть
    #: контрагента тому, кто пришёл поправить срок. У заведения его нет и быть не может.
    kept = None

    def standing(self) -> dict:
        """Чем форма открывается, когда адрес не спрашивал поиска. У заведения — ничем."""
        return {}

    def asked(self, name):
        """Что спросили об этом поле — из отправки или из адреса, смотря откуда пришли.

        Приставку помнит форма, а не читающий её: имена в отправке носят её, имена начальных
        значений — нет, и место, где эти два чтения расходятся, здесь одно.
        """
        if self.is_bound:
            return self.data.get(self.add_prefix(name))
        return self.initial.get(name)

    def clean(self):
        """Бессрочность и дата конца вместе не заводятся (ADR 0031).

        Состояний срока три, и два разом не бывает: полка отвечает на «когда кончается», а
        договор, у которого конца нет по соглашению и при этом заведена дата, отвечает на
        этот вопрос дважды и по-разному. Разрешать спор молча — выбирать за читателя то, чего
        он не выбирал; поэтому отказ, и поэтому названы оба выхода из него.

        Отказ не принадлежит ни одному из двух полей: виновата пара, и указать пальцем на
        одну её половину значило бы назначить виноватым то, что читатель, может быть, как раз
        и хотел оставить.
        """
        cleaned = super().clean()
        if cleaned.get("is_perpetual") and cleaned.get("valid_until") is not None:
            raise ValidationError(
                "Бессрочный договор конца срока не имеет: снимите бессрочность или очистите "
                "дату — состояний срока три, и два разом не бывает."
            )
        return cleaned

    def fill(self, terms):
        """Четыре условия, как их набрали, — в строку условий этого договора.

        Невыбранный вид ложится пустотой, а не пустой строкой: «вид не заведён» — одно
        состояние, и два его написания в одном столбце рано или поздно разойдутся в запросе,
        который ищет одно из них.
        """
        terms.counterparty = self.cleaned_data["counterparty"]
        terms.kind = self.cleaned_data["kind"] or None
        terms.is_perpetual = self.cleaned_data["is_perpetual"]
        terms.auto_prolongs = self.cleaned_data["auto_prolongs"]
        terms.save()


class ContractCorrectionForm(ContractTermsForm):
    """Правка условий на экране договора — та половина бумаги, которую узнают позже скана.

    Те же условия, что и у заведения, но у договора, который уже есть: форма поднимается с
    заведённым в полях и отправляется на адрес самого договора. Сверх общей половины она не
    спрашивает ничего — название, номер и скан правят на странице документа, и второе их
    место было бы второй правдой о них (ADR 0030).
    """

    def __init__(self, data=None, files=None, *, contract, **kwargs):
        """Договор приходит с экрана, на котором стоит форма, а не полем.

        Полем он был бы вторым ответом на «какой договор правим» рядом с адресом — и правом
        написать в чужую бумагу для всякого, кто подставит ключ в отправку.
        """
        self.contract = contract
        self.kept = contract.attached_terms().counterparty_id
        super().__init__(data, files, **kwargs)

    def standing(self) -> dict:
        """Чем форма открывается: условиями, как они на договоре стоят сейчас (`recorded`)."""
        return recorded(self.contract)

    def save(self):
        """Условия и срок — одной отправкой и одной транзакцией.

        Срок ложится на документ, остальные четыре условия — в строку рядом с ним, и врозь
        они не ложатся никогда: договор, у которого дату записали, а бессрочность нет,
        прочитался бы полкой как спор, которого форма только что не допустила.
        """
        with transaction.atomic():
            self.contract.valid_until = self.cleaned_data["valid_until"]
            self.contract.save()
            self.fill(self.contract.attached_terms())
        return self.contract


class ContractEntryForm(ContractTermsForm):
    """Бумага и обязательство разом: документ вида «Договор» и его условия одной отправкой.

    Поля документа стоят здесь, а не берутся у формы его реквизитов: та спрашивает пять полей
    у документа любого вида и не спрашивает названия — оно взялось из имени файла в пачке
    (ADR 0008). Здесь же название спрашивают первым, скана может не быть вовсе, а «кем выдан»
    и «ревизия» договору не нужны: договор не выдают, его подписывают двое.
    """

    title = forms.CharField(
        label="Название",
        # Длина столбца: название длиннее не сохранилось бы, и отказать о нём здесь честнее,
        # чем обрезать по дороге в базу.
        max_length=512,
        error_messages={"required": "Укажите название: полку договоров читают по названиям."},
    )
    doc_no = forms.CharField(required=False, label="Номер", max_length=128)
    issued_at = forms.DateField(required=False, label="Дата договора", widget=DateEntered())
    #: Скан необязателен, и это не послабление: договор заводят, держа в руках номер и срок, а
    #: бумагу сканируют потом. Пустой файл — обычное состояние документа, и страница документа
    #: уже умеет о нём говорить.
    scan = forms.FileField(
        required=False,
        label="Скан",
        # Что принимается и сколько, сказано один раз и там, где это решается: подсказка под
        # полем, фильтр в диалоге выбора и отказ отклонённому файлу не должны быть тремя
        # разными изложениями одного правила.
        help_text=f"{ACCEPTED_NAMES}, до {FILE_LIMIT // MEGABYTE} МБ.",
        widget=forms.ClearableFileInput(attrs={"accept": ACCEPTED_IN_A_DIALOG}),
    )

    def __init__(self, *args, user, **kwargs):
        """Пятым — и только тому, кто ведёт больше одной организации, — чья это будет бумага.

        Вывести ответ не из чего: здания в этой форме нет, в отличие от пачки документов, где
        БЦ и говорит, чья это полка (ADR 0010), и расходный договор здания не называет вовсе
        (ADR 0033). Отказать вместо вопроса значило бы оставить администратора двух клиентов
        без заведения договора, а ведущему одного список из единственного значения повторял бы
        то, что он и так знает, — тем же доводом, каким полка заводит или не заводит колонку
        «Организация».
        """
        # Организации, чьи данные этот сотрудник вправе вести, — спрошенные у самих
        # организаций, где и живёт довод о том, чьи они (ADR 0005). Читаются один раз: вопрос
        # задаётся и при сборке формы, и при её проверке.
        self.administered = list(Org.objects.administered_by(user))
        super().__init__(*args, user=user, **kwargs)
        if len(self.administered) > 1:
            self.fields["org"] = forms.ModelChoiceField(
                queryset=Org.objects.filter(pk__in=[org.pk for org in self.administered]),
                label="Организация",
                # Пустого выбора нет: чья это бумага — не то, что можно оставить на
                # усмотрение, и «выберите» здесь было бы значением, которое всё равно
                # придётся отклонить.
                empty_label=None,
                error_messages={"invalid_choice": "Выберите организацию, которую вы ведёте."},
            )

    @property
    def scan_is_chosen_again(self) -> bool:
        """Унёс ли отказ с собой выбранный файл.

        Всё остальное отказ возвращает в поля, а файл вернуть некому: браузер не отдаёт
        разметке выбранный путь, и никакое значение в `<input type="file">` не вписать. Значит,
        сказать об этом словами — единственное, что остаётся: молчание тут прочиталось бы как
        «файл приложен», и договор завёлся бы без скана, который прикладывали дважды. Тем же
        доводом загрузка плана говорит вслух о плане с будущей датой (ADR 0005).

        Спрошено о самой отправке, а не о поле: отказать могли о сроке, а потерян всё равно
        файл. И только когда он был — строка о файле, которого не выбирали, отправила бы
        читателя искать потерю, которой не было.
        """
        return bool(self.is_bound and self.files and self.errors)

    def clean_scan(self):
        """Скан судят по содержимому, а не по имени, — тем же чтением, каким его судит пачка.

        Переименованный `.exe` сканом не становится, и правило это не переписывается сюда:
        два изложения того, что такое PDF, разошлись бы, и разошедшимся оказалось бы то,
        которым файл принимают.
        """
        uploaded = self.cleaned_data["scan"]
        if uploaded is None:
            return None
        refusal = refusal_for(uploaded.name, uploaded.size, head_of(uploaded))
        if refusal is not None:
            raise ValidationError(f"Скан не сохранён: {refusal}.")
        return uploaded

    def clean(self):
        """Чья это будет бумага — и чем её содержимое узна́ют в следующей пачке.

        Ведущий одну организацию не спрашивается вовсе, и ответ за него берётся отсюда —
        оттуда же, откуда берётся сам список. Ведущий несколько отвечает полем, и тогда здесь
        не решается ничего: поле уже проверило, что названная организация — из тех, что он
        ведёт, и чужая не становится его от того, что её ключ вписали в отправку. Спрошено
        через `self.fields`, а не через пустоту в ответе: поле, о котором уже отказали,
        оставляет ту же пустоту, и подставленная под неё первая организация была бы ответом за
        читателя, которому как раз отказали.

        Отпечаток содержимого считается и кладётся рядом с файлом — тем же чтением, каким его
        считает пачка: им пакетная загрузка и узнаёт скан, который уже лежит на полке.
        Отказа по нему здесь нет: повторный файл пачка называет сообщением, а не отказом, и
        второе решение о том же рядом с первым было бы вторым ответом на один вопрос.
        """
        cleaned = super().clean()
        if "org" not in self.fields:
            # Ровно одна: форма собирается только тому, кто ведёт хоть одну организацию, — тот
            # же вопрос задан на самом запросе (`ContractListView.administers_anything`), и
            # спрошенный здесь второй раз он был бы вторым ответом на один вопрос.
            cleaned["org"] = self.administered[0]
        uploaded = cleaned.get("scan")
        if uploaded is not None:
            cleaned["file_hash"] = digest_of(uploaded)
        return cleaned

    def save(self):
        """Документ и строка условий рядом с ним — одной транзакцией.

        Строку условий заводит сама модель, по одной на всякий документ вида «Договор» и
        заполненную или нет (ADR 0035); форме остаётся вписать в неё то, что спросили. Завести
        её здесь второй раз значило бы завести второе правило о том, у кого условия бывают.

        Одной транзакцией потому, что документ без условий на полку договоров попадает, а
        отвечает на ней прочерками во всех колонках: заведённый так, он читался бы как пачка
        сканов, которых никто не разбирал.
        """
        with transaction.atomic():
            contract = Document.objects.create(
                org=self.cleaned_data["org"],
                kind=Document.Kind.CONTRACT,
                title=self.cleaned_data["title"],
                doc_no=self.cleaned_data["doc_no"],
                issued_at=self.cleaned_data["issued_at"],
                valid_until=self.cleaned_data["valid_until"],
                file_uri=self.cleaned_data["scan"] or "",
                file_hash=self.cleaned_data.get("file_hash"),
            )
            self.fill(contract.attached_terms())
        return contract
