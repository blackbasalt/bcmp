"""Род договора — доходный или расходный: одно правило, выданное в двух формах.

Род нигде не хранится. Он выводится из вида, потому что каждый из пяти видов стоит на одной
стороне: аренда помещений и доп услуги — то, за что платят нам, эксплуатация, капитальные
работы и поставка ТМЦ — то, за что платим мы. Один предмет по разные стороны даёт два вида, а
не один вид с двумя родами: клининг, проданный арендатору, — доп услуги, клининг, купленный у
подрядчика, — эксплуатация. Столбец рядом с видом был бы второй правдой о том же, и разошлись
бы они на первом же договоре, которому вид поправили.

Спрашивают об этом с двух концов, и каждый конец не должен нести свою копию. Экран договора
держит один договор и хочет его род словом в шапке; полка держит запрос и хочет тем же родом
сузиться. Поэтому правило раздаётся в обеих формах и выведено здесь один раз — тот же приём,
каким `space_kind` раздаёт вид помещения, `plan_completeness` — полноту плана,
`leases.occupancy` — занятость, а `parties.occasions` — повод.

Два чтения решаются здесь и больше нигде:

- **У договора без вида рода нет, и это не ошибка.** Вид может пустовать (ADR 0035): сорок
  сканов пачкой попадают на полку раньше, чем кто-нибудь проставит им вид. Строка без рода
  честнее строки, которой род угадали, и обе формы отвечают на пустой вид пустотой — значение
  `None`, условие, не находящее ничего.
- **Спрашивают о договоре, а не об условиях.** Полка стоит на документах: изоляция — это
  `Document.org` и ничто другое (ADR 0006), название и номер — тоже его поля. Поэтому и
  значение берётся с документа, и условие пишется для запроса документов, хотя вид лежит в
  `ContractTerms` сбоку: спрашивающий держит в руках договор, а не его половину.

Бухгалтерских слов здесь нет ни одного, и это отказ, а не случайность: статьи затрат
существуют затем, чтобы их суммировать, а BCMP не хранит сумм — ни договора, ни начислений,
ни оплат. «Эксплуатация» уцелела потому, что это собственное слово УК про обслуживание
здания, а не строка сметы; «Капитальные работы» названы работами, потому что это то, что
делают, а не то, во что вкладывают. Проверяется этот отказ поиском по коду: слово, которого
на экране быть не должно, не должно встречаться и в комментарии, объясняющем почему (спека
0007).

Собственных тестов у модуля нет — ровно как у `space_kind`, `plan_completeness` и
`occupancy`: его читают экраны, и экраны его проверяют. Отдельный тест был бы вторым
изложением одного правила, и однажды они разошлись бы.
"""

from django.core.exceptions import ImproperlyConfigured
from django.db.models import Q

from documents.models import ContractTerms

#: Ключи двух родов — те же слова, которыми род назван в отборе и в шапке договора.
INCOME = "income"
EXPENSE = "expense"

#: Оба рода в том порядке, в каком их читают: сначала то, за что платят нам. Порядок задан
#: здесь, чтобы список отбора и подпись в шапке не разошлись расстановкой.
GENERA = ((INCOME, "Доходный"), (EXPENSE, "Расходный"))

#: Само правило: на какой стороне стоит каждый вид. Один словарь, а не две связки условий,
#: потому что читают его дважды — раз о договоре в руках, раз о запросе, — и две связки были
#: бы двумя местами, где о новом виде придётся вспомнить, с одним из них забытым.
#:
#: Пятёрка полна намеренно: вид, которого здесь нет, — это вид, о роде которого никто не
#: договорился, и молчаливое «расходный» по остатку назвало бы род, которого не выводили.
STANDS_ON = {
    ContractTerms.Kind.LEASE: INCOME,
    ContractTerms.Kind.EXTRA_SERVICES: INCOME,
    ContractTerms.Kind.OPERATION: EXPENSE,
    ContractTerms.Kind.CAPITAL_WORKS: EXPENSE,
    ContractTerms.Kind.SUPPLY: EXPENSE,
}

#: Виды, о стороне которых здесь не сказано, — и их не бывает.
#:
#: Проверено на запуске, а не тестом: правило раздаётся экранам, и шестой вид, заведённый на
#: модели и не расставленный тут, молча пропал бы из обеих форм — строка без рода и полка, не
#: находящая его ни доходным, ни расходным. `raise`, а не `assert`: отказ, снимаемый ключом
#: запуска, — это отказ, которого в одном из запусков нет.
_UNPLACED = set(ContractTerms.Kind.values) - set(STANDS_ON)
if _UNPLACED:
    raise ImproperlyConfigured(
        "Род выводится из вида, и каждый вид стоит на одной из двух сторон. Не расставлены: "
        + ", ".join(sorted(_UNPLACED))
        + " — допишите их в STANDS_ON."
    )


def genus_of(document) -> str | None:
    """Род договора — или `None`, если вид ему ещё не проставлен.

    Документ, который не договор, условий не носит вовсе, и ответ ему тот же: рода у акта не
    бывает, и спрашивать о нём не ошибка.
    """
    terms = document.attached_terms()
    if terms is None:
        return None
    return STANDS_ON.get(terms.kind)


def being(genus: str) -> Q:
    """Условие, отбирающее договоры одного рода, — `genus_of`, сказанное запросу.

    Тот же словарь и та же сторона, так что род, напечатанный в строке, и род, которым полку
    сузили, разойтись не могут.

    Виды перечисляются, а не отрицаются: `kind__in` не находит договор без вида ни на одной
    стороне, тогда как «всё, что не доходное» записало бы его в расходные — то самое
    угаданное, от которого правило и отказывается. Род, которого нет вовсе, сужает полку до
    пустой, а не отбрасывается: полка не заявляет отбора, которого не делала (ADR 0014).
    """
    return Q(terms__kind__in=[kind for kind, side in STANDS_ON.items() if side == genus])
