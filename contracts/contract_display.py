"""Как договор читается на экране: сколько полки показано и чем кончается каждый срок.

Всё, что раздел говорит словами, читается через этот файл, и читает его не одна полка:
вид, род, контрагент и «Кончается» стоят и в строке таблицы, и в шапке экрана договора.
Написанные по разу на экран, они разошлись бы — и один договор на двух экранах сказал бы о
себе разное. Строка счёта — фраза, собранная
здесь, а не число, поставленное рядом с таблицей: «Показано 12 из 340 договоров» отвечает
на вопрос, а «12 / 340» — величина, о которой читателю приходится догадываться. Тот же
приём, что «Показано 47 из 583 помещений» под полкой помещений и «нанесено 47 из 82» под
планом.

Согласование с числительным считается здесь, а не собирается в разметке: «из 1 договоров»
читается на экране как сбой, а не как один договор.

Дата берётся у раздела документов, а не пишется заново, и это единственное, что здесь взято
у другого раздела: на полке договоров и на полке документов стоит одна и та же строка одной
и той же таблицы, и два написания её срока были бы двумя ответами о нём на двух экранах. У
Стороны и у помещения ничего общего с документом нет, оттого там дата и написана своя.
Прочерк же приходит из общего для всего проекта `or_missing`, который читают все пять
разделов, и своим он не бывает ни у кого.

Что считать незаполненным — не здесь: обе незаполненности называет ещё и строка счёта
числом-ссылкой, поэтому правило у них общее и лежит в `gaps`. Клетка и находка обязаны
сходиться: читатель, нажавший «срок не заведён у 12», ищет в таблице ровно то, что было
написано в клетке.
"""

from building_passport.passport_display import or_missing
from documents.document_display import NBSP, day

from . import gaps, genus

#: Род каждым из двух ключей — то же слово и в том же написании, каким род назван в отборе.
#: Собран из `genus.GENERA`, а не переписан сюда: два списка родов разошлись бы на первом же
#: переименовании, и шапка сказала бы одно, а условие отбора — другое.
GENUS_SAID = dict(genus.GENERA)

#: Что строка говорит под «Кончается», когда конца у срока нет по самому соглашению
#: (ADR 0031). Словом, а не пустой клеткой: пустота здесь значила бы ещё и «никто не
#: завёл», и один договор из двух спрятался бы за другим.
PERPETUAL = "бессрочный"

#: И что она говорит, когда срок не заведён вовсе. Тем же словом, каким находка названа на
#: строке счёта: читатель, нажавший «срок не заведён у 12», обязан узнать в клетке то самое,
#: чего он искал.
UNRECORDED = "срок не заведён"

#: Автопролонгация — приписка к любому из трёх состояний, а не четвёртое из них: она
#: меняет то, что строка говорит, а не то, попадает ли она на полку (ADR 0031).
PROLONGS = "продлевается автоматически"


def contracts_shown(shown: int, whole: int) -> str:
    """«Показано 12 из 340 договоров» — сколько полки оставил стоять отбор.

    Два числа, а не одно: суженная полка обязана назвать и размер того, что сузили, иначе
    читатель держит 12, которые не с чем сравнить.

    Существительное согласуется со вторым числом, а не с первым: правит им «из». Сказуемое
    остаётся «Показано» при любом числе — подлежащее здесь «12 из 340», часть чего-то, а
    часть среднего рода, как бы мала она ни была.

    «из» требует родительного падежа, поэтому форм тут две, а не три — «из 1 договора», «из
    2 договоров», «из 5 договоров». Это правило `room_display.rooms_shown` и
    `party_display.parties_shown`, а не трёхчастное согласование
    `document_display.agreeing_with`: прогнанная через него, строка прочла бы «из 2
    договора». Написано здесь заново потому, что это то же правило с другим словом, а
    общего у двух разделов — одна грамматика.
    """
    contracts = "договора" if whole % 10 == 1 and whole % 100 != 11 else "договоров"
    return f"Показано {shown} из {whole}{NBSP}{contracts}"


def kind_said(contract) -> str:
    """Вид договора, как он назван в строке, — или прочерк, пока его не проставили.

    Прочерк, а не пустота: вид может пустовать (ADR 0035), но это работа, которую кто-то
    ещё не сделал, а не ответ о договоре. Ставит его `or_missing`, одним правилом на весь
    проект.

    Незаполненность спрашивается у `gaps`, а не решается здесь: тем же правилом считается
    находка «вид не заведён у N» под таблицей и сужается полка по её ссылке, и клетка,
    решавшая это сама, однажды показала бы вид там, где находка обещала прочерк.

    Слово берётся у модели — `get_kind_display()`, — а не переписывается сюда: тем же
    словом вид назван в списке, из которого его выберут, и в шапке экрана договора.
    """
    if gaps.kind_is_unrecorded(contract):
        return or_missing(None)
    return contract.attached_terms().get_kind_display()


def genus_said(contract) -> str | None:
    """Род договора словом — «Доходный», «Расходный», — или ничего, пока вид не проставлен.

    Выводится из вида и нигде не хранится (ADR 0030): каждый из пяти видов стоит на одной
    стороне, и колонка рядом с видом была бы второй правдой о том же.

    Пустота у договора без вида — это ответ, а не пробел в правиле: взяться роду неоткуда,
    пока никто не сказал, что за бумага в руках (ADR 0035). Прочерк за него ставит
    `or_missing`, как и за всякое незаполненное поле, — строка без рода честнее строки,
    которой род угадали.

    Ключ, которого в словаре нет, роняет KeyError, а не молчит: роды перечислены здесь оба, и
    третий, взявшийся из `genus`, — это род, о слове для которого никто не договорился.
    Молчаливая пустота на его месте прочиталась бы как «вид не проставлен».

    Слово ставится здесь, а не в `genus`: там живёт правило — на какой стороне стоит каждый
    вид, — и раздаётся оно ключом и условием запроса, а всё, что раздел говорит словами,
    читается через этот файл. Так же и вид: правило о нём на модели, а прочерк за
    незаведённым — в `kind_said` строкой выше.
    """
    stands_on = genus.genus_of(contract)
    return GENUS_SAID[stands_on] if stands_on is not None else None


def counterparty_said(contract) -> str:
    """Контрагент — вторая сторона договора, или прочерк, пока её не завели.

    Своё поле, и никогда не «Кем выдан»: договор не выдают, его подписывают двое, и
    `issuer_party`, заполненный по недосмотру, контрагентом тут не притворится.
    """
    terms = contract.attached_terms()
    counterparty = terms.counterparty if terms is not None else None
    return or_missing(counterparty.name if counterparty is not None else None)


def ending_said(contract) -> str:
    """Что строка говорит под «Кончается»: одно из трёх состояний и приписка к нему.

    Три состояния, а не два (ADR 0031): срок до числа, бессрочный, не заведён. Полка
    отвечает на «когда кончается», и одна пустая клетка на два последних смысла тихо
    спрятала бы договор, истекающий через месяц.

    Заведённая дата перевешивает взведённую бессрочность, и это разрешение спора, а не его
    порядок: два условия, спорящих между собой, — данные, которых ни одна форма не заводит,
    но прочесть их полке придётся, и «бессрочный» над заведённым концом срока спрятал бы
    ровно тот договор, ради которого полка стоит.

    Автопролонгация приписывается к любому из трёх, потому что она о другом: не о том,
    когда срок кончается, а о том, что будет, когда он кончится.
    """
    said = _state_of(contract)
    terms = contract.attached_terms()
    if terms is not None and terms.auto_prolongs:
        return f"{said}{NBSP}· {PROLONGS}"
    return said


def _state_of(contract) -> str:
    """Одно из трёх состояний срока, без приписки о продлении.

    Третье спрашивается у `gaps` первым, хотя по порядку оно последнее: тем же правилом
    считается находка «срок не заведён у N», и клетка, решавшая это сама, разошлась бы с
    числом, которое её же и обещает.
    """
    if gaps.term_is_unrecorded(contract):
        return UNRECORDED
    if contract.valid_until is not None:
        return day(contract.valid_until)
    return PERPETUAL
