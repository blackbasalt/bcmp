"""Две находки полки договоров — вид не заведён и срок не заведён, каждая в двух формах.

Полка называет их числами под таблицей, и каждое число — ссылка: «вид не заведён у 12»
считается по показанному, а нажатие сужает полку ровно до тех двенадцати. Считают и сужают
разные концы — строки в руках и запрос к базе, — и каждый конец не должен нести свою копию
правила: разошлись бы они молча, и число под таблицей перестало бы сходиться с таблицей,
которую открывает его же ссылка. Тот же приём, каким `contracts/genus.py` раздаёт род,
`space_kind` — вид помещения, а `leases.occupancy` — занятость.

Пробел здесь — не пустое поле, а пустое поле, которого быть не должно (ADR 0015, ADR 0031):

- **вид не заведён** — обычное состояние, а не поломка (ADR 0035): сорок сканов попадают на
  полку раньше, чем кто-нибудь проставит им вид. Число называет размер работы, которую
  кто-то ещё не сделал, и потому стоит на строке счёта, а не поднимает тревогу.
- **срок не заведён** — это пустая дата *и* невзведённая бессрочность разом. Бессрочный
  договор сюда не попадает: конца срока у него нет по самому соглашению, и это ответ, а не
  пробел. Одна пустота на два смысла тихо спрятала бы договор, истекающий через месяц, — от
  чего ADR 0031 и написан.

Собственных тестов у модуля нет, как и у `genus.py`: обе формы читает полка, и полка их
проверяет — числом на строке счёта и тем, что открывает его ссылка.
"""

from django.db.models import Q

#: Имена условий в адресе — те же, какими они объявлены полями отбора. Написаны здесь, чтобы
#: ссылка под таблицей и чтение отбора брали имя отсюда, а не набирали его каждый по разу;
#: что поле с таким именем на форме и правда есть, `shelf_search` проверяет на запуске.
NO_KIND = "no_kind"
NO_TERM = "no_term"


def kind_is_unrecorded(contract) -> bool:
    """Не проставлен ли вид у договора в руках.

    Спрашивается через `attached_terms`, потому что спрашивают о договоре, а не об его
    половине: документ, которому строку условий не завели вовсе, — та же незаполненность,
    и отвечать на него исключением значило бы уронить полку из-за пробела, ради счёта
    которого она и стоит.
    """
    terms = contract.attached_terms()
    return terms is None or not terms.kind


def kind_unrecorded() -> Q:
    """`kind_is_unrecorded`, сказанное запросу.

    Пустая строка проверяется наравне с `NULL`: поле объявлено `null=True, blank=True`, и
    форма, сохранившая невыбранный список, кладёт в него именно пустую строку. Договор без
    строки условий ловится тем же условием — внешнее соединение отдаёт по такому `NULL`.
    """
    return Q(terms__kind__isnull=True) | Q(terms__kind="")


def term_is_unrecorded(contract) -> bool:
    """Не заведён ли срок у договора в руках — пустой конец при невзведённой бессрочности."""
    if contract.valid_until is not None:
        return False
    terms = contract.attached_terms()
    return terms is None or not terms.is_perpetual


def term_unrecorded() -> Q:
    """`term_is_unrecorded`, сказанное запросу."""
    return Q(valid_until__isnull=True) & (
        Q(terms__is_perpetual=False) | Q(terms__is_perpetual__isnull=True)
    )
