"""Как одна учётная карточка читается на своём экране: чем Сторона названа и что при ней есть.

Собрано здесь, а не в разметке, по той же причине, по какой собраны разделы паспорта и
реквизиты документа: что экран говорит о Стороне — это правило о данных, а не о вёрстке.
Какие поля в шапке, в каком порядке их читают, что берётся из карточки, а что из самой
Стороны — решается один раз и в питоне, а шаблону остаётся напечатать готовое. Прочерк за
пустым значением сюда не попадает: его ставит `or_missing`, одним правилом на весь проект.

Порядок шапки — порядок, в котором знакомятся: чья это карточка, как Сторону зовут, по
какому номеру её узнают, юрлицо она или физлицо, чем занимается, — и лишь потом поводы,
которые все предыдущие строки уже объяснили. По алфавиту он не сортируется: экран отвечает
на вопрос «кто это», а у этого вопроса есть порядок.

Четыре блока под шапкой — платёжные реквизиты, контактные лица, аренды и документы — своих
правил почти не имеют: это списки строк, и решается о них немногое — через какого привратника
берутся строки, чем они сужены до одной организации и бывает ли такой список у этой Стороны
вообще. Решается это здесь, а не в представлении, потому что ответы у списков общие: чем
сужены аренды, тем же сужены и документы, а «у физлица контактных лиц не бывает» — та же
половина правила, по которой её день рождения стоит в шапке.
"""

from dataclasses import dataclass
from typing import Any

from leases.models import Lease

from .models import Party
from .occasions import occasions_of
from .party_display import day, kind_said, occasion_said


@dataclass(frozen=True)
class Field:
    """Строка шапки. Пустое значение остаётся None — прочерк ставит `or_missing`.

    Названа, а не только подписана: разметка несёт имя в `data-field`, так что на поле можно
    указать снаружи, ничего не зная о вёрстке вокруг него.

    Того же вида, что и `Field` на странице документа, и написана заново, а не взята оттуда:
    у Стороны и у документа общая одна лишь форма строки — подпись, имя и значение, — и
    импорт между двумя разделами ради трёх полей первым покажется лишним, когда любой из двух
    тронется с места. Тем же доводом в этом проекте написаны дважды и запись даты, и
    согласование числительного.
    """

    name: str
    label: str
    value: Any


def stands_for_herself(party) -> bool:
    """Физлицо: представителя у неё нет и быть не может.

    Одно правило, читаемое отовсюду, и потому написанное один раз: у физлица нет блока
    контактных лиц вовсе (ADR 0025), и оттого же её день рождения стоит в шапке — повесить
    личный повод больше не на кого. Тем же правилом решается, какие створки ей достанутся и
    какая отправка отвечает 404. Сказанное в двух местах, оно однажды показало бы физлицу
    блок, в котором никого не бывает, или потеряло бы её день рождения совсем.
    """
    return party.kind == Party.Kind.PERSON


def particulars(record, *, naming_the_organisation: bool) -> tuple[Field, ...]:
    """Всё, чем Сторона названа на своём экране, готовое к печати.

    Организация — первой и только тому, кто ведёт больше одного клиента: у него одна и та же
    Сторона стоит на полке двумя строками, экраны этих двух карточек различаются одними лишь
    данными, и без имени клиента читатель не скажет, который из двух открыл. Ведущему одного
    клиента она сообщала бы на каждом экране то, что он и так знает. Спрашивается это о
    читателе, а не о карточке, — тем же условием, каким полка заводит свою колонку
    «Организация», и оно приходит уже решённым: два места, считающих, сколько клиентов у
    читателя, — это два ответа на один вопрос.

    День рождения — только у физлица, и это не украшение шапки, а единственное место, где он
    может стоять: контактных лиц у физлица нет (ADR 0025), и повесить личный повод больше не
    на кого. У юрлица строки нет вовсе, а не стоит пустой: день рождения ТОО — это дни
    рождения его людей, и они в блоке контактных лиц.

    Сфера деятельности берётся с самой Стороны, а не с карточки: это публичный факт без двух
    версий, и продублированный по карточкам он дал бы 637 расходящихся мнений о том, чем
    занимается «Центр крепежных систем» (ADR 0020).
    """
    party = record.party
    fields = []
    if naming_the_organisation:
        fields.append(Field("org", "Организация", record.org.name))
    fields += [
        Field("name", "Название", party.name),
        # Оба в одной строке, потому что у Стороны есть один из двух и никогда оба: у
        # юрлица БИН, у физлица ИИН. Так же названа и колонка полки.
        Field("bin_iin", "БИН/ИИН", party.bin_iin),
        # «Вид» — то же слово, каким проект делит помещения на арендопригодные, МОП и
        # технические: вид делит сущности одного типа. ОПФ отдельным полем не бывает — она
        # уже суффикс названия (ADR 0025).
        Field("kind", "Вид", kind_said(party)),
        Field("line_of_business", "Сфера деятельности", party.line_of_business),
    ]
    if stands_for_herself(party):
        fields.append(Field("born_on", "День рождения", day(record.born_on)))
    return tuple(fields)


def occasions_said(record, on) -> tuple[str, ...]:
    """Поводы карточки, ближайший первым, — «кого поздравить», записанное словами.

    Читается тем же `occasions_of`, каким полка считает свою колонку, и пишется тем же
    `occasion_said`, каким полка её печатает: правило одно, и разложенное по двум экранам
    оно однажды назвало бы ближайшим не то, чем сузилась полка (ADR 0023, ADR 0027).

    Весь список, а не один ближайший: экран держит одну карточку и может позволить себе
    перечислить, а «кого поздравить» у юрлица с тремя контактными лицами — это три ответа, из
    которых читателю нужен не обязательно первый.

    Дни рождения контактных лиц стоят и здесь, и в блоке под шапкой, и это не два места одного
    факта: там записано, что известно о человеке, здесь — когда наступит повод. Выведенный
    профессиональный праздник в блоке контактных лиц не стоит и стоять не может — он ничей.
    """
    return tuple(occasion_said(occasion) for occasion in occasions_of(record, on))


def contacts_of(record):
    """Люди внутри Стороны, с которыми организация имеет дело, — или ничего вовсе.

    Ничего, а не пустой список, если Сторона физлицо: «не заведено» и «не бывает» — разные
    ответы, и пустой блок сказал бы первое там, где верно второе. Что физлицо не делают своим
    же представителем, решается один раз — в `stands_for_herself`.
    """
    return None if stands_for_herself(record.party) else record.contacts.all()


def payment_details_of(record):
    """Куда платить Стороне — комплектами, основной первым.

    Порядок держит сама модель, а не этот вызов: он значит то же самое и в админке, где
    комплекты заводят, и заданный здесь второй раз он однажды разошёлся бы с нею.

    Банк берётся тем же запросом, что и комплекты: на экране он назван, а спрошенный
    разметкой — это запрос на каждую строку.
    """
    return record.payment_details.select_related("bank")


def leases_of(record):
    """Аренды Стороны у этой организации — «где сидит ТОО «Альфа»», спрошенное с её стороны.

    Сужены до помещений организации, чья это карточка, ровно как их сужает
    `occupancy.rooms_of_each_record`: Сторона общая, а её аренды — нет, потому что кто видит
    помещение, тот видит его аренды (ADR 0018). Карточка DownTown показывает помещения
    DownTown и молчит о том, что то же юрлицо снимает у другого клиента платформы.

    Второго привратника здесь нет и не нужно: чья это карточка, решено до вызова, в
    `PartyRecord.objects.visible_to` (ADR 0020), а `org` помещения — это та же организация.

    Порядок — свой у самой аренды, новейшая первой: что действует сегодня, спрашивают куда
    чаще, чем что действовало в 2019-м. Прошлые аренды не убираются и за складку не прячутся:
    вопрос экрана — «где Сторона сидит и сидела», а какая из них сегодняшняя, написано в её же
    сроке. Складка карточки помещения отвечает на другой вопрос — «кто здесь сидит сейчас», — и
    там сегодняшние надо было отделить.

    Итога нет и не будет: сложить арендуемые площади значит посчитать дважды помещение,
    стоящее внутри другого, а какое из двух вложений перед нами, по строке не видно
    (ADR 0015, ADR 0019).
    """
    return Lease.objects.filter(tenant=record.party, space__org=record.org).select_related(
        "space", "space__building"
    )


def documents_issued_by(record, documents):
    """Документы, где Сторона стоит «Кем выдан», — её бумажный след, достижимый от неё.

    Документы приходят уже через свой привратник (ADR 0006) и сужаются здесь до организации,
    чья это карточка, — тем же доводом, что и аренды выше: читатель двух клиентов не должен
    видеть на карточке DownTown акт, выданный той же Стороной другому клиенту.

    Ни вид, ни срок здесь не спрашиваются: блок отвечает «что от неё есть», а что это за
    бумага — вопрос её собственного экрана, куда каждая строка и ведёт.
    """
    return documents.filter(issuer_party=record.party, org=record.org)
