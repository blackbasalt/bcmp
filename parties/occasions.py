"""Повод — день в году, к которому готовят поздравление: одно правило в двух формах.

Об одном и том же спрашивают с двух концов, и каждый конец не должен нести свою копию.
Полка Сторон держит сотни строк и хочет у каждой ближайший повод — одной колонкой и без
запроса на строку, — а ещё условие отбора «кого поздравить на этой неделе». Экран Стороны
держит одну учётную карточку и хочет весь её список поводов подряд. Оба вида стоят здесь по
одной причине: правило одно, и разложенное по двум местам оно однажды назвало бы на экране
ближайшим не то, чем сузилась полка. Тот же приём, что `space_kind` завёл для вида,
`plan_completeness` для полноты плана и `leases.occupancy` для занятости.

Три чтения решаются здесь и больше нигде:

- **Личный повод хранится, профессиональный выводится** (ADR 0023). День рождения заведён
  руками: у юрлица он висит на контактном лице, у физлица — на самой учётной карточке, и
  оба лежат в карточке, потому что дата рождения есть персональные данные и второй
  управляющей компании, знакомой с тем же юрлицом, их не показывают (ADR 0020).
  Профессиональный праздник выводится из сферы деятельности Стороны и справочника и не
  хранится нигде: «День строителя» у трёхсот арендаторов — это триста копий одной даты,
  которые разойдутся. Таблицы `Occasion` нет.
- **Правило разрешается в дату того года, о котором спрашивают** (ADR 0027). Справочник
  хранит либо число и месяц, либо «n-й такой-то день недели такого-то месяца», и года не
  хранит нигде; ближайший повод — первое наступление правила начиная с сегодняшнего дня,
  так что в декабре колонка честно называет январь следующего года.
- **Сегодняшний повод ещё не прошёл.** «Кого поздравить», спрошенное утром того самого дня,
  не должно отвечать «через год»: наступление ищется начиная с дня, о котором спрашивают, а
  не со следующего за ним.

Отбор знает три значения и ни одного свободного числа дней: «на этой неделе» — по
воскресенье текущей недели, «в этом месяце» — по последнее число текущего месяца, «в
ближайшие 90 дней» — скользящим окном от сегодня. Две календарные границы и одна
скользящая — ровно то, что говорят сами слова; свободное число пригласило бы ввести 0 и
3650.

Собственных тестов у модуля нет — ровно как у `space_kind`, `plan_completeness` и
`occupancy`: его читают экраны, и экраны его проверяют. Читателей двое: полка — колонкой и условием отбора, — и
экран Стороны, перечисляющий поводы одной карточки, и все три чтения проверены
`parties/test_shelf.py`, `parties/test_search.py` и `parties/test_page.py`. Отдельный тест был
бы вторым изложением одного правила, и однажды они разошлись бы.
"""

import calendar
from collections import defaultdict
from dataclasses import dataclass
from datetime import date, timedelta
from functools import partial
from uuid import UUID

from dictionary.models import DictProfessionalHoliday

from .models import ContactPerson

#: Как назван личный повод. Один и тот же у контактного лица и у физлица: это один род
#: повода, а чей он — сказано отдельно, в `whose`, и у физлицо́вого повода не сказано вовсе,
#: потому что имя Стороны и так стоит в строке.
BIRTHDAY = "День рождения"

#: На этой неделе — по воскресенье текущей недели включительно. Календарная неделя, а не
#: «семь дней вперёд»: «на этой неделе» по-русски значит именно эту неделю, и в среду оно
#: кончается в воскресенье, а не в следующую среду.
THIS_WEEK = "week"
#: В этом месяце — по последнее число текущего месяца включительно. Тоже календарная
#: граница, и по той же причине.
THIS_MONTH = "month"
#: В ближайшие 90 дней — окно от сегодня, а не квартал календаря: девяносто дней вперёд
#: одинаковы, откуда ни считай, а «этот квартал» тридцать первого марта не значит ничего.
WITHIN_90_DAYS = "90-days"

#: Три значения, которые отбор принимает. Порядок от ближнего к дальнему: список читают
#: сверху вниз, и «кого поздравить» спрашивают начиная с самого срочного.
WINDOWS = [
    (THIS_WEEK, "На этой неделе"),
    (THIS_MONTH, "В этом месяце"),
    (WITHIN_90_DAYS, "В ближайшие 90 дней"),
]


@dataclass(frozen=True)
class Occasion:
    """Один повод: когда он и как он называется.

    Одна форма на оба рода — хранимый день рождения и выведенный профессиональный праздник,
    — потому что применение у них одно: «кого поздравить». Два класса означали бы два списка
    и два отбора там, где вопрос один (ADR 0023).

    Порядок задаётся ключом при сортировке, а не сравнением самого повода: «чей» бывает
    пустым, и None рядом со строкой сравнить нельзя — два дня рождения на одно число уронили
    бы экран ровно в том редком случае, ради которого второй ключ и нужен.
    """

    #: День, в который повод наступает, — уже разрешённый в год, о котором спрашивают. Здесь
    #: год есть, и в справочнике его нет: справочник хранит правило, а это его наступление.
    on: date
    #: «День рождения» или «День строителя». Профессиональный берёт короткое имя справочника:
    #: в справочнике оно и заведено ради тех мест, где длинному не хватает ширины, а колонка
    #: полки — первое такое место.
    name: str
    #: Чей повод, если это чей-то: ФИО контактного лица. У профессионального его нет — он
    #: про отрасль, а не про человека, — и у дня рождения физлица тоже: имя Стороны уже стоит
    #: в строке, и повторить его значило бы сказать одно дважды.
    whose: str | None = None


def _falls_on(holiday: DictProfessionalHoliday, year: int) -> date:
    """Правило справочника, разрешённое в дату названного года (ADR 0027).

    Обе формы читаются здесь и в одном месте, потому что строка справочника несёт ровно
    одну из них и `CheckConstraint` это утверждает: заполнено число — правило по числу,
    заполнены неделя и день недели — правило по дню недели.
    """
    if holiday.day is not None:
        return date(year, holiday.month, holiday.day)
    return _weekday_of_month(year, holiday.month, holiday.week_of_month, holiday.weekday)


def occasions_of(record, on: date) -> tuple[Occasion, ...]:
    """Все поводы одной учётной карточки, ближайший первым, — список для экрана Стороны.

    Хранимые личные и выведенный профессиональный вместе и вперемешку: разложенные по двум
    спискам, они заставили бы читателя самого свести их в один, чтобы понять, кого
    поздравлять раньше.

    Своих запросов не жалеет — и в этом вся разница с `nearest_for_each_record`: здесь одна
    карточка, а там сотни строк, и то, что спрашивают у строки, спрашивают сотни раз.

    Читает его экран Стороны. Правило стоит здесь, а не там, потому что складывает личные
    поводы с профессиональным тем же `_folded`, что и колонка полки, — заведённое на своём
    экране, оно было бы вторым изложением одного правила.
    """
    return _folded(
        born_on=record.born_on,
        contacts=[
            (contact.born_on, contact.full_name)
            for contact in record.contacts.all()
            if contact.born_on is not None
        ],
        holidays=DictProfessionalHoliday.objects.filter(
            line_of_business_id=record.party.line_of_business_id
        )
        if record.party.line_of_business_id
        else [],
        on=on,
    )


def nearest_for_each_record(records, on: date) -> dict[UUID, Occasion]:
    """Ближайший повод каждой карточки — то же правило, сказанное всей полке сразу.

    Отображение «ключ карточки → ближайший повод», по которому строка и читается: карточка,
    у которой повода нет вовсе, в него не попадает, и колонка ставит прочерк.

    Два запроса на всю полку и ни одного на строку — приём, которым уже держатся
    `tenants_of_each_room` и `rooms_of_each_record`: контактные лица всех карточек берутся
    одним запросом, праздники всех названных сфер деятельности — вторым. Правило разрешается
    питоном, а не запросом: «второе воскресенье августа» не выражается сравнением дат ни в
    SQLite, ни в PostgreSQL одинаково, и справочник потому и хранит правило (ADR 0027).

    Строки берутся как есть и вычитываются один раз. Полка передаёт уже прочитанное —
    вместе со Стороной и её сферой деятельности, — и на ней это не стоит ни запроса: считается
    ровно по тем строкам, которые будут напечатаны, и разойтись с таблицей над собой колонке
    нечем. Отбор передаёт ещё не прочитанный набор, и его чтение — цена того, что правило
    разрешается питоном, а не запросом; `falling_within` говорит об этой цене вслух.

    Своего привратника здесь нет и не нужно: чьи это карточки, решено до вызова, в
    `PartyRecord.objects.visible_to` (ADR 0020), а контактные лица берутся у самих карточек
    — личный повод лежит в карточке, и чужая карточка сюда не доходит.
    """
    records = list(records)
    birthdays = defaultdict(list)
    for record_id, born_on, full_name in ContactPerson.objects.filter(
        record__in=records, born_on__isnull=False
    ).values_list("record_id", "born_on", "full_name"):
        birthdays[record_id].append((born_on, full_name))

    holidays = defaultdict(list)
    for holiday in DictProfessionalHoliday.objects.filter(
        line_of_business_id__in={
            record.party.line_of_business_id
            for record in records
            if record.party.line_of_business_id
        }
    ):
        holidays[holiday.line_of_business_id].append(holiday)

    nearest = {}
    for record in records:
        folded = _folded(
            born_on=record.born_on,
            contacts=birthdays.get(record.pk, ()),
            holidays=holidays.get(record.party.line_of_business_id, ()),
            on=on,
        )
        if folded:
            nearest[record.pk] = folded[0]
    return nearest


def falling_within(records, on: date, window: str) -> list[UUID]:
    """Ключи карточек, у которых повод наступает не позже конца окна, — «кого поздравить».

    Условие отбора, а не отдельный экран: «кого поздравить на этой неделе» — это полка,
    отвечающая на вопрос, и её же строки, её же счёт и её же адрес.

    Спрашивается о ближайшем поводе, а не о каждом: если ближайший дальше конца окна, то
    дальше и все остальные, — так что одного ответа хватает на оба чтения и второго обхода
    не нужно.

    Питоном, а не запросом, и потому списком ключей, а не условием: правило разрешается в
    дату вычислением, и полка сужается по тому, что вычислено. Отбор от этого не перестаёт
    быть отбором — он по-прежнему только убирает строки из ответа привратника (ADR 0020).

    Стоит это одного лишнего чтения полки: строки читаются здесь, чтобы сложить их поводы, а
    сужённый набор экран читает заново. Плата берётся только с того запроса, в котором условие
    названо, и только с него: `narrow` обязан вернуть набор строк, а не список, — иначе полка
    Сторон одна из трёх отвечала бы не тем, чем отвечают две другие (`bcmp.shelf`).
    """
    last_day = _ends_on(window, on)
    return [
        record_id
        for record_id, occasion in nearest_for_each_record(records, on).items()
        if occasion.on <= last_day
    ]


def _ends_on(window: str, on: date) -> date:
    """Последний день окна отбора — включительно.

    Все три считаются от дня, о котором спрашивают, вперёд: ближайший повод не бывает
    позади, так что окно — это всегда «отсюда и до», и нижняя граница у всех трёх одна.
    """
    if window == THIS_WEEK:
        # По воскресенье: `isoweekday` считает понедельник первым, так что до конца недели
        # остаётся ровно семь минус сегодняшний номер дней, а в само воскресенье — ноль.
        return on + timedelta(days=7 - on.isoweekday())
    if window == THIS_MONTH:
        return date(on.year, on.month, calendar.monthrange(on.year, on.month)[1])
    if window == WITHIN_90_DAYS:
        return on + timedelta(days=90)
    # Назван вслух, а не отдан самому дальнему окну молча: сюда доходит только то, что уже
    # прошло проверку списком, так что чужое значение здесь — не ввод из адреса, а ошибка в
    # коде, и полка, тихо ответившая кварталом на неизвестное окно, спрятала бы её.
    raise ValueError(f"Неизвестное окно повода: {window!r}")


def _folded(*, born_on, contacts, holidays, on: date) -> tuple[Occasion, ...]:
    """Хранимые личные поводы и выведенный профессиональный, сложенные вместе и по близости.

    Одно место, где два рода становятся одним списком, — и потому и полка, и экран Стороны
    получают их в одном порядке. Разложи их по двум местам, и однажды экран назвал бы
    ближайшим не то, чем полка сузилась.
    """
    # Свой день рождения физлица идёт без «чей»: имя Стороны уже стоит в строке. Читается
    # безусловно, а не только у физлица: поле для того и заведено, и второе правило о том,
    # кому оно позволено, разошлось бы с формой, которая одна его и заполняет.
    personal = [(born_on, None)] if born_on is not None else []
    occasions = [
        Occasion(on=_next_after(partial(_born, day), on), name=BIRTHDAY, whose=whose)
        for day, whose in personal + list(contacts)
    ]
    occasions += [
        Occasion(on=_next_after(partial(_falls_on, rule), on), name=rule.short_name)
        for rule in holidays
    ]
    # По близости, а название и «чей» лишь доводят порядок до однозначного: два повода на
    # один день должны ложиться в один и тот же порядок от запроса к запросу, иначе колонка
    # называла бы то одного, то другого без всякой причины.
    return tuple(sorted(occasions, key=lambda one: (one.on, one.name, one.whose or "")))


def _next_after(day_of, on: date) -> date:
    """Первое наступление годового правила начиная с дня, о котором спрашивают.

    С самого дня, а не со следующего за ним: сегодняшний день рождения ещё не прошёл, и
    «кого поздравить», спрошенное утром, не должно отвечать «через год».
    """
    this_year = day_of(on.year)
    return this_year if this_year >= on else day_of(on.year + 1)


def _born(born_on: date, year: int) -> date:
    """День рождения, разрешённый в названный год: число и месяц те же, год — спрашиваемый.

    Двадцать девятое февраля в невисокосном году отдаётся двадцать восьмым, а не
    пропускается: родившегося в этот день поздравляют раз в год, как всех, и повод,
    исчезающий из списка на три года из четырёх, читался бы как «дня рождения нет».
    """
    if born_on.month == 2 and born_on.day == 29 and not calendar.isleap(year):
        return date(year, 2, 28)
    return born_on.replace(year=year)


def _weekday_of_month(year: int, month: int, week: int, weekday: int) -> date:
    """«n-й такой-то день недели такого-то месяца», разрешённый в дату.

    «Последняя» неделя — не «пятая» и не «четвёртая», и считается с конца месяца: в августе
    воскресений бывает и четыре, и пять, так что День шахтёра — последнее воскресенье — и
    День работников торговли — четвёртое — расходятся в половине лет.

    Обе ветви — сдвиг по кругу из семи дней: `% 7` попадает на нужный день недели, ни разу
    не выйдя за месяц, потому что от первого числа вперёд и от последнего назад до
    ближайшего такого дня недели меньше недели пути.
    """
    if week == DictProfessionalHoliday.WeekOfMonth.LAST:
        last = date(year, month, calendar.monthrange(year, month)[1])
        return last - timedelta(days=(last.isoweekday() - weekday) % 7)
    first = date(year, month, 1)
    return first + timedelta(days=(weekday - first.isoweekday()) % 7 + 7 * (week - 1))
