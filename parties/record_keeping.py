"""Ведение учётной карточки — три створки на экране Стороны и то, что каждая заводит.

Свою карточку администратор организации ведёт **всегда**, независимо от того, знает ли эту
Сторону кто-то ещё: телефоны, счета и дни рождения меняются каждую неделю, и вести их через
звонок в поддержку значит не вести вовсе (ADR 0021). Общая половина Стороны — название,
БИН, род, сфера — этими створками не трогается: она правится по другому правилу и с другим
радиусом (ADR 0028).

**Спрашивается ровно то, что висит на карточке.** Комплект платёжных реквизитов, контактное
лицо, день рождения физлица — и ничего сверх: у контактного лица не спрашивают БИН, потому
что он не Сторона и в отношения ни с кем не вступает, а у комплекта не спрашивают ни слова о
лицензии банка, потому что справочник о ней молчит и молчать будет (ADR 0022).

**Карточка — не поле, а экран, на котором стоит форма.** Ни одна из трёх её не спрашивает:
чья это карточка, решено до формы — привратником `visible_to` и правом на запись, — и поле
поставило бы второй ответ рядом с адресом. Тот же приём, каким аренда берёт помещение с
карточки, а не с формы.
"""

from django import forms
from django.db import transaction

from building_passport.date_entered import DateEntered
from dictionary.models import DictBank

from .models import ContactPerson, PartyRecord, PaymentDetails
from .party_display import bank_said


class PaymentDetailsForm(forms.ModelForm):
    """Комплект платёжных реквизитов: банк из справочника, счёт, КБе и пометка «основной».

    Комплектами, а не полями карточки: счёт в тенге и счёт в валюте живут вместе, и заведение
    нового не затирает прежний — платёжка, выписанная позавчера, должна сходиться с тем, что
    на экране. Оттого форма только заводит: закрытый комплект остаётся рядом с открытым.

    Про лицензию банка не спрашивается ничего, и это не забывчивость формы, а решение
    справочника: BCMP неоткуда узнать, что лицензию отозвали, и поле о ней через год уверенно
    сказало бы неправду (ADR 0022).
    """

    class Meta:
        model = PaymentDetails
        fields = ("bank", "account", "kbe", "is_primary")
        labels = {"is_primary": "Основной комплект"}
        # Сказано на самом поле, а не в разметке: пометив второй комплект, администратор ждёт
        # двух основных и решит, что первый потерялся, — а два изложения одного правила
        # разошлись бы, и разошедшимся оказалось бы то, которое читает заполняющий форму.
        help_texts = {
            "is_primary": (
                "Прежний основной остаётся на карточке — с него снимается только пометка."
            )
        }
        error_messages = {"bank": {"required": "Выберите банк из справочника."}}

    def __init__(self, *args, record, **kwargs):
        """Карточка приходит с экрана, на котором стоит форма, а не полем в отправке."""
        super().__init__(*args, **kwargs)
        self.instance.record = record
        bank = self.fields["bank"]
        # Справочник целиком, в своём алфавите: сорок три ликвидированных банка без БИК стоят
        # в нём наравне с действующими — комплект, заведённый при АТФБанке, называет АТФБанк,
        # и вычеркнутый из списка банк сделал бы позавчерашнюю платёжку нечитаемой.
        bank.queryset = DictBank.objects.order_by("name")
        # Список открывается ни на чём: банк решает, куда уйдут деньги, и проставленный за
        # отправителя был бы принят без взгляда — тот же довод, что у рода Стороны.
        bank.empty_label = "Выберите банк"
        # Название вместе с БИК, тем же написанием, каким банк назван в заведённом комплекте:
        # выбирают его по БИК, и список, называющий одно лишь название, отправил бы выбирать
        # по написанию.
        bank.label_from_instance = bank_said

    def save(self, commit=True):
        """Завести комплект — и, если он основной, снять пометку с прежнего.

        Один основной на карточке, и держит это форма, а не база: ограничение в базе
        отклонило бы первое из двух сохранений, которыми переносят пометку, и перенести её
        стало бы нечем (`PaymentDetails.is_primary` о том же). Здесь оба сохранения — одно
        действие и одна транзакция, так что двух помеченных комплектов на экране не бывает
        ни на мгновение.

        Пометка снимается, а комплект остаётся: основной — свойство сегодняшнего дня, а не
        признак того, что счёт жив. Непомеченный комплект платёжку позавчерашнего дня
        подтверждает ровно так же.

        `commit=False` не снимает её ни с кого: этой формой ничего не пишется, а карточка, у
        которой основного не стало от несостоявшегося сохранения, — то самое расхождение
        экрана с базой, ради которого оба сохранения и держат одной транзакцией.
        """
        with transaction.atomic():
            if commit and self.instance.is_primary:
                PaymentDetails.objects.filter(record=self.instance.record, is_primary=True).update(
                    is_primary=False
                )
            return super().save(commit)


class ContactPersonForm(forms.ModelForm):
    """Контактное лицо: имя, должность, телефон, почта и день рождения — и ни слова о БИН.

    Стороной он не является: аренду на него не заводят, на полку Сторон он не попадает и БИН
    ему не нужен — спрошенный, тот сделал бы из директора вторую строку рядом с его же ТОО.
    Тот же человек, зарегистрированный как ИП, — отдельная Сторона, и заводят её на полке.

    Обязательно одно имя. Человек, о котором известен только телефон, и человек, о котором
    известна только должность, — оба записи, которые стоит держать; форма, требующая всего
    сразу, не пропустила бы ни одну из них.
    """

    class Meta:
        model = ContactPerson
        fields = ("full_name", "position", "phone", "email", "born_on")
        # День рождения набирается полем даты и читается им же обратно: набранное от руки
        # «14 марта 1980 г.» браузер не прочтёт, и поле вернётся пустым.
        widgets = {"born_on": DateEntered()}
        error_messages = {
            "full_name": {"required": "Укажите ФИО: список контактных лиц читают по именам."}
        }

    def __init__(self, *args, record, **kwargs):
        """Карточка приходит с экрана — та же договорённость, что и у комплекта выше."""
        super().__init__(*args, **kwargs)
        self.instance.record = record


class BirthdayForm(forms.ModelForm):
    """День рождения физлица — единственное, что ведут на самой карточке.

    Личный повод существует и там, где повесить его не на кого: контактных лиц у физлица нет
    (ADR 0025), и день рождения стоит в шапке её экрана, а не в чьей-то строке. На карточке, а
    не на Стороне, потому что дата рождения есть персональные данные и второй управляющей
    компании, знакомой с тем же человеком, их не показывают (ADR 0020, ADR 0023).

    Правкой, а не заведением: поле одно, и заведённое однажды исправляют им же — вторая форма
    для того же поля была бы вторым местом, где записан один день.
    """

    class Meta:
        model = PartyRecord
        fields = ("born_on",)
        widgets = {"born_on": DateEntered()}
