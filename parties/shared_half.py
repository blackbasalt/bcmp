"""Общая половина Стороны — четыре столбца на всю систему и правило, кому их править.

Название, БИН/ИИН, юрлицо/физлицо и сфера деятельности — одна строка на одно юрлицо
(ADR 0020). Платёжные реквизиты, контактные лица и дни рождения к ним не относятся: те висят
в учётной карточке, ведутся её организацией всегда и правятся `record_keeping`.

**Правит администратор организации — но только пока карточка на эту Сторону есть у него
одного.** Появилась вторая — общее замирает и меняется администратором платформы. Решает
радиус правки, а не её сложность: занять свободный БИН не вредит никому, а переименовать
«АО «Kaspi Bank»» в «каспи» значит поменять экраны второй управляющей компании, которая с этим
банком тоже работает и об этой правке не узнает (ADR 0028).

**Замёрзшая половина не показывается формой, которая потом откажет.** Экран говорит, что
Сторона знакома не только нам, и на этом останавливается: показанная форма с отказом на
отправке читается как сломанный экран — то же правило, каким сотруднику без флага не
достаётся ни одной створки раздела (ADR 0005).

**Занятый БИН здесь отказ, а не сообщение**, и это не расхождение со створкой заведения, а
та же самая мысль с другого конца. Заведение на занятый БИН находит Сторону, которая уже есть,
и заводит карточку на неё; правка на занятый БИН просит две строки реестра сделать одной —
слить их некому, и БИН перестал бы быть ответом на вопрос «кто это».
"""

from dataclasses import dataclass

from django import forms

from dictionary.models import DictLineOfBusiness

from .models import Party, PartyRecord
from .party_display import KINDS


def bin_iin_entered(value: str) -> str:
    """БИН/ИИН без пробелов: «091 240 012 345» и «091240012345» — один и тот же номер.

    Списанный с бумаги и списанный со счёта, они разошлись бы двумя Сторонами одного юрлица —
    тем самым дублем, ради которого поле объявлено обязательным обоим родам. Чистятся только
    пробелы: в номере чужого реестра дефис может значить что-то, пробел — никогда, а форма,
    вынимающая из строки одни цифры, испортила бы такой номер молча.

    Одно правило на заведение и на правку, и написанное один раз намеренно: вся защита реестра
    от дублей стоит на этом номере, и вторая, разошедшаяся, чистка завела бы ровно тот дубль,
    от которого номер и оберегает.
    """
    return "".join(value.split())


def known_by_others(record) -> bool:
    """Знает ли эту Сторону кто-то, кроме организации этой карточки, — правило замирания.

    Спрашивается обо всей системе, а не через привратник `visible_to`: замирает общее оттого,
    что правка дотянулась бы до чужого экрана, и чужая карточка, которой читателю не видно,
    от невидимости не перестаёт существовать. Узнаётся при этом ровно один бит — что Сторона
    знакома кому-то ещё, — и это та же утечка, что и на створке заведения, принятая вслух в
    том же объёме: ни кому, ни с каких пор, ни что о ней записано (ADR 0021, ADR 0028).
    """
    return (
        PartyRecord.objects.filter(party_id=record.party_id).exclude(pk=record.pk).exists()
    )


class SharedHalfForm(forms.ModelForm):
    """Правка четырёх столбцов Стороны — тех же четырёх, о которых спрашивает заведение.

    Створка заведения спрашивает их же и написана своими полями, а не этими: там из ответов
    получается `get_or_create`, для которого занятый БИН — исход, а не отказ, и там же
    спрашивается пятое поле, организация, которого у правки нет вовсе. Общими у двух форм
    остаются те два места, где расхождение стоило бы дорого: чистка номера
    (`bin_iin_entered`) и слово, которым называется род (`KINDS`).

    Формой правится Сторона, а не карточка: экран стоит на карточке, и Сторона берётся с неё
    же — полем в отправке она была бы вторым ответом на вопрос, на который уже ответил адрес.
    """

    #: Тем же словом, каким род назван в шапке и на створке заведения: «Организация» на этих
    #: экранах значит арендатора платформы, и `get_kind_display()` сказал бы, что ТОО «Альфа»
    #: есть клиент BCMP.
    kind = forms.ChoiceField(
        label="Юрлицо / физлицо",
        choices=KINDS.items(),
        error_messages={"invalid_choice": "Выберите юрлицо или физлицо."},
    )
    line_of_business = forms.ModelChoiceField(
        # Справочник целиком, в своём алфавите, — тот же, которым сужается полка.
        queryset=DictLineOfBusiness.objects.order_by("name"),
        required=False,
        label="Сфера деятельности",
        # Пустой выбор говорит словами: ни у одной из 699 Сторон сферы не проставлено, и
        # форма, требующая её, отказала бы в правке названия тому, чью отрасль справочник
        # ещё не знает.
        empty_label="Сфера неизвестна",
        error_messages={"invalid_choice": "Выберите сферу деятельности из списка."},
    )

    class Meta:
        model = Party
        fields = ("name", "bin_iin", "kind", "line_of_business")
        labels = {"name": "Название", "bin_iin": "БИН/ИИН"}
        help_texts = {
            "bin_iin": "Обязателен и юрлицу, и физлицу: без него одну Сторону заведут дважды."
        }
        error_messages = {
            "name": {"required": "Укажите название: полку Сторон читают по названиям."},
            "bin_iin": {
                "required": "Укажите БИН/ИИН: без него одну и ту же Сторону заведут дважды.",
                # Занятый номер называет одну лишь Сторону — тот же один бит, каким отвечает
                # створка заведения, и ни слова о том, кто её завёл (ADR 0021).
                "unique": "Сторона с этим БИН/ИИН уже заведена — у одного юрлица одна строка.",
            },
        }

    def __init__(self, *args, **kwargs):
        """Обязательность БИН объявляет форма, а не столбец.

        `null=True` со столбца не снимается: 62 Стороны чужих баз и вымышленные арендаторы
        посева живут по своим правилам, а форма обязана требовать номер обоим родам —
        отпущенный ею, он дал бы Сторону, которую в реестре не отличить (ADR 0028).
        """
        super().__init__(*args, **kwargs)
        self.fields["bin_iin"].required = True

    def clean_bin_iin(self):
        """Номер чистится до проверки на занятость: пробел не должен делать его свободным."""
        return bin_iin_entered(self.cleaned_data["bin_iin"])


@dataclass(frozen=True)
class SharedHalf:
    """Общая половина, как её держит экран: правится или замерла.

    Два состояния одного, а не два предложения: стоят они в одном месте экрана и говорят об
    одних и тех же четырёх столбцах в два разных дня жизни Стороны. Замирание не хранится
    отдельным полем, а читается по отсутствию формы: два признака одного состояния однажды
    разошлись бы, и разошедшимся оказался бы тот, который читает разметка.

    Экрану, на котором правка не предлагается никому, не достаётся и этого: сотрудник без
    флага администратора не видит ни формы, ни объяснения, почему её нет, — объяснять
    отсутствие того, чего ему не полагается, значит рассказывать о чужом праве.
    """

    #: Форма правки — или `None`, если общее замерло.
    form: SharedHalfForm | None = None

    @property
    def frozen(self) -> bool:
        return self.form is None
