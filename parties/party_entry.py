"""Заведение Стороны — форма на полке и то, что одна её отправка заводит.

Прежде Сторону заводил только администратор платформы, в админке. Предмет изменился:
учётная карточка — телефоны, счета, люди, дни рождения — меняется каждую неделю, и вести её
через звонок в поддержку значит не вести вовсе (ADR 0021). Заводит теперь администратор
организации, и это стоит ровно одного бита, о котором ниже.

**Спрашивается общая половина Стороны и ничего сверх неё**: название, БИН/ИИН,
юрлицо/физлицо и сфера деятельности — одна строка на всю систему (ADR 0020). Телефоны, счета
и контактные лица живут в учётной карточке, заводятся на её собственном экране и этой формой
не спрашиваются: здесь они удлинили бы створку вчетверо ради того, что почти всегда узнают
позже самой Стороны.

Пятым — и только тому, кто ведёт больше одной организации, — спрашивается, чья это будет
карточка. Вывести ответ не из чего: здания в этой форме нет, в отличие от пачки документов,
где БЦ и говорит, чья это полка (ADR 0010). Отказать вместо вопроса значило бы оставить
администратора двух клиентов вовсе без заведения Стороны, а ведущему одного список из
единственного значения повторял бы то, что он и так знает, — тем же доводом, каким полка
заводит или не заводит колонку «Организация».

**БИН/ИИН обязателен обоим родам.** Вся защита от дублей стоит на нём: совпадающих названий
у юрлиц в Казахстане сколько угодно, и без идентификатора «ТОО «Альфа»» заведут дважды. Все
699 настоящих строк несут его — ровно 12 цифр, без пропусков и без повторов. Обязательность
объявляет форма, а не столбец: `null=True` со столбца не снимается, потому что 62 Стороны
чужих баз живут по своим правилам (ADR 0028).

Формат при этом не проверяется, а пробелы вычищаются, и это разные решения. Двенадцати цифр
форма не требует: незнание ИИН значит, что Сторону заводят рано, а не что цифры надо
пересчитать, а 62 Стороны чужих баз несут номера чужих реестров. Но «091 240 012 345»,
списанное с бумаги, и «091240012345», списанное со счёта, — один и тот же БИН, и пропущенные
как есть они завели бы ровно тот дубль, ради которого поле и сделано обязательным. Чистятся
только пробелы и ничто больше: дефис в номере чужого реестра может значить что-то, пробел —
никогда.

**Занятый БИН не отказ, а сообщение.** Сторона одна на систему, и заводить вторую с тем же
номером незачем; вместо этого администратор получает учётную карточку на ту, что уже есть, а
общая половина остаётся как была — переименовать «АО «Kaspi Bank»» значило бы поменять экраны
второй управляющей компании, которая об этой правке не узнает (ADR 0028). Сказано об этом
прямо: администратор узнаёт, что это юрлицо кому-то в системе знакомо, — и больше ничего: ни
кому, ни с каких пор, ни что о нём записано. Утечка принята вслух ровно в этом объёме
(ADR 0021).

**Карточка заводится вместе со Стороной.** Без неё заведённая Сторона не попала бы на
собственную полку: полка Сторон — полка учётных карточек (ADR 0020), и Сторона без карточки
осталась бы в реестре, находимой при заведении аренды и не видной тому, кто её только что
завёл.
"""

from typing import NamedTuple

from django import forms
from django.db import transaction

from dictionary.models import DictLineOfBusiness

from .models import Org, Party, PartyRecord
from .party_display import KINDS


class Entered(NamedTuple):
    """Чем кончилась одна отправка: карточкой — и тем, что для неё пришлось завести.

    Три ответа едут вместе, потому что это один ответ — что стало со Стороной: карточка,
    открываемая следом, и два признака, по которым решается, есть ли что сказать словами.
    Заведена карточка или уже была — вопрос отдельный от того, заведена ли Сторона: полка
    может уже знать её, и тогда отправка не завела ничего вовсе.
    """

    #: Учётная карточка моей организации на эту Сторону — та, чей экран откроется следом.
    record: PartyRecord
    #: Заведена ли сама Сторона, или БИН был занят.
    party_entered: bool
    #: Заведена ли карточка, или Сторона уже стояла на моей полке.
    record_entered: bool


class PartyEntryForm(forms.Form):
    """Название, БИН/ИИН, род и сфера — общая половина Стороны, и ничего сверх неё.

    Пятое поле, организация, заводится только тому, кто ведёт больше одной: довод целиком
    выше, в модуле, где рядом стоит и то, почему остальные четыре — это все четыре.
    """

    name = forms.CharField(
        label="Название",
        # Длина столбца: название длиннее не сохранилось бы, и отказать о нём здесь честнее,
        # чем обрезать по дороге в базу.
        max_length=255,
        error_messages={"required": "Укажите название: полку Сторон читают по названиям."},
    )
    bin_iin = forms.CharField(
        label="БИН/ИИН",
        max_length=32,
        # Обоим родам, и сказано это на самом поле: единственная защита от дублей во всём
        # разделе — этот номер, и отказ должен объяснять, почему поле не пропускают пустым.
        help_text="Обязателен и юрлицу, и физлицу: без него одну Сторону заведут дважды.",
        error_messages={
            "required": "Укажите БИН/ИИН: без него одну и ту же Сторону заведут дважды."
        },
    )
    kind = forms.ChoiceField(
        # «Юрлицо / физлицо» и не «Род»: два значения называют вопрос между собой, а слова для
        # пары словарь не несёт. Заголовки берутся оттуда же, откуда их берут оба экрана
        # раздела, — у модели юрлицо названо «Организация», и на этих экранах это слово
        # значит арендатора платформы.
        label="Юрлицо / физлицо",
        # Список открывается ни на чём: род решает, будет ли у Стороны блок контактных лиц и
        # где повиснет день рождения, и проставленный за отправителя был бы принят без
        # взгляда. Тот же довод, что у вида документа и у даты перепланировки (ADR 0005).
        choices=[("", "Выберите юрлицо или физлицо"), *KINDS.items()],
        error_messages={"invalid_choice": "Выберите юрлицо или физлицо."},
    )
    line_of_business = forms.ModelChoiceField(
        # Справочник целиком, в своём алфавите, — тот же, которым сужается полка.
        queryset=DictLineOfBusiness.objects.order_by("name"),
        required=False,
        label="Сфера деятельности",
        # Необязательная, и пустой выбор говорит это словами: ни у одной из 699 Сторон сферы
        # не проставлено, а форма, требующая её, отказала бы в заведении поставщика, чью
        # отрасль справочник ещё не знает. Без сферы не выводится профессиональный повод — и
        # это всё, чего Сторона лишается.
        empty_label="Сфера неизвестна",
        error_messages={"invalid_choice": "Выберите сферу деятельности из списка."},
    )

    def __init__(self, *args, user, **kwargs):
        super().__init__(*args, **kwargs)
        # Организации, чьи данные этот сотрудник вправе вести, — спрошенные у самих
        # организаций, где и живёт довод о том, чьи они (ADR 0005). Читаются один раз: вопрос
        # задаётся и при сборке формы, и при её проверке.
        self.administered = list(Org.objects.administered_by(user))
        if len(self.administered) > 1:
            self.fields["org"] = forms.ModelChoiceField(
                queryset=Org.objects.filter(pk__in=[org.pk for org in self.administered]),
                label="Организация",
                # Пустого выбора нет: чья это карточка — не то, что можно оставить на
                # усмотрение, и «выберите» здесь было бы значением, которое всё равно
                # придётся отклонить.
                empty_label=None,
                error_messages={
                    "invalid_choice": "Выберите организацию, которую вы ведёте.",
                },
            )

    def clean_bin_iin(self):
        """БИН/ИИН без пробелов: «091 240 012 345» и «091240012345» — один и тот же номер.

        Списанный с бумаги и списанный со счёта, они разошлись бы двумя Сторонами одного
        юрлица — тем самым дублем, ради которого поле и объявлено обязательным. Чистятся
        только пробелы: в номере чужого реестра дефис может значить что-то, пробел — никогда,
        а форма, вынимающая из строки одни цифры, испортила бы такой номер молча.
        """
        return "".join(self.cleaned_data["bin_iin"].split())

    def clean(self):
        """Чья это будет карточка.

        Ведущий одну организацию не спрашивается вовсе, и ответ за него берётся здесь —
        оттуда же, откуда берётся сам список. Ведущий несколько отвечает полем, и тогда здесь
        не решается ничего: поле уже проверило, что названная организация — из тех, что он
        ведёт, и чужая не становится его от того, что её ключ вписали в отправку.
        """
        cleaned = super().clean()
        if "org" not in self.fields:
            # Ровно одна: форма собирается только тому, кто ведёт хоть одну организацию, — тот
            # же вопрос задан на самом запросе (`PartyListView.administers_anything`), и
            # спрошенный здесь второй раз он был бы вторым ответом на один вопрос.
            cleaned["org"] = self.administered[0]
        return cleaned

    def save(self) -> Entered:
        """Сторона по этому БИН и карточка организации на неё — обе, если их ещё нет.

        Обе через `get_or_create`, и не ради краткости: БИН уникален, и две отправки,
        разошедшиеся на миллисекунду, иначе кончились бы `IntegrityError` вместо второй
        карточки на одну Сторону. Он же и выражает правило заведения на занятый БИН: найденная
        Сторона возвращается как есть, и набранные название, род и сфера до неё не доходят.
        Правка общей половины — вопрос отдельный, со своим радиусом и своим тикетом (ADR 0028);
        створка заведения не путь к ней ни для кого.

        Одной транзакцией: Сторона, заведённая без карточки, не попала бы ни на чью полку и
        осталась бы в реестре строкой, которую её заводивший больше не видит.
        """
        with transaction.atomic():
            party, party_entered = Party.objects.get_or_create(
                bin_iin=self.cleaned_data["bin_iin"],
                defaults={
                    "name": self.cleaned_data["name"],
                    "kind": self.cleaned_data["kind"],
                    "line_of_business": self.cleaned_data["line_of_business"],
                },
            )
            record, record_entered = PartyRecord.objects.get_or_create(
                party=party, org=self.cleaned_data["org"]
            )
        return Entered(record, party_entered, record_entered)
