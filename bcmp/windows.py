"""Окно вперёд: «на этой неделе», «в этом месяце», «в ближайшие 90 дней».

Две полки спрашивают этими самыми словами, и спрашивают о разном. Полка Сторон — «кого
поздравить», и окно закрывает ближайший повод; полка договоров — «что кончается», и окно
закрывает конец срока. А сами три окна — не про повод и не про срок: это чтение календаря,
и читатель, перешедший с одной полки на другую, обязан встретить у «на этой неделе» одну и
ту же границу. Написанные по разу на раздел, они разошлись бы молча — в среду одна полка
кончала бы неделю воскресеньем, а другая следующей средой, и ни один экран об этом не
сказал бы.

Поэтому окно стоит в проекте, а не в разделе, — ровно тем же доводом, каким здесь же стоит
`shelf`: полке, берущей его у соседа, до предметной области соседа дела нет.

Три значения и ни одного свободного числа дней. Свободное пригласило бы ввести 0 и 3650, и
экран отвечал бы то ни о чём, то обо всём. Две границы календарные — «на этой неделе» и «в
этом месяце» значат по-русски именно эту неделю и этот месяц, — и одна скользящая:
девяносто дней вперёд одинаковы, откуда ни считай, тогда как «этот квартал» тридцать
первого марта не значит ничего.

Собственных тестов у модуля нет: его читают две полки, и обе его проверяют — отбором,
который сузил, и строками, которые остались.
"""

import calendar
from datetime import date, timedelta

#: На этой неделе — по воскресенье текущей недели включительно. Календарная неделя, а не
#: «семь дней вперёд»: «на этой неделе» по-русски значит именно эту неделю, и в среду оно
#: кончается в воскресенье, а не в следующую среду.
THIS_WEEK = "week"
#: В этом месяце — по последнее число текущего месяца включительно. Тоже календарная
#: граница, и по той же причине.
THIS_MONTH = "month"
#: В ближайшие 90 дней — окно от сегодня, а не квартал календаря: девяносто дней вперёд
#: одинаковы, откуда ни считай, а «этот квартал» тридцать первого марта не значит ничего.
WITHIN_90_DAYS = "90-days"

#: Три значения, которые отбор принимает, — ключ и то слово, каким окно названо на экране.
#: Порядок от ближнего к дальнему: список читают сверху вниз, и спрашивают начиная с самого
#: срочного.
WINDOWS = [
    (THIS_WEEK, "На этой неделе"),
    (THIS_MONTH, "В этом месяце"),
    (WITHIN_90_DAYS, "В ближайшие 90 дней"),
]


def ends_on(window: str, on: date) -> date:
    """Последний день окна — включительно.

    Все три считаются от дня, о котором спрашивают, вперёд, и нижняя граница у них одна:
    окно — это всегда «отсюда и до».

    Неизвестное окно названо вслух, а не отдано самому дальнему молча: сюда доходит только
    то, что уже прошло проверку списком, так что чужое значение здесь — не ввод из адреса, а
    ошибка в коде, и полка, тихо ответившая кварталом, спрятала бы её.
    """
    if window == THIS_WEEK:
        # По воскресенье: `isoweekday` считает понедельник первым, так что до конца недели
        # остаётся ровно семь минус сегодняшний номер дней, а в само воскресенье — ноль.
        return on + timedelta(days=7 - on.isoweekday())
    if window == THIS_MONTH:
        return date(on.year, on.month, calendar.monthrange(on.year, on.month)[1])
    if window == WITHIN_90_DAYS:
        return on + timedelta(days=90)
    raise ValueError(f"Неизвестное окно: {window!r}")
